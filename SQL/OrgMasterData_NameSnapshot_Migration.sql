UPDATE R SET
	R.DIVISION_NAME = DIV.DIVISION_NAME,
	R.DEPARTMENT_CODE = DEP.DEPARTMENT_CODE,
	R.DEPARTMENT_NAME = DEP.DEPARTMENT_NAME,
	R.SECTION_NAME = SEC.SECTION_NAME
FROM [dbo].[TB_R_DOCUMENT] R
LEFT JOIN [dbo].[TB_M_DIVISION] DIV ON DIV.DIVISION_CODE = R.DIVISION
LEFT JOIN [dbo].[TB_M_DEPARTMENT] DEP ON DEP.DEPARTMENT_ID = R.DEPARTMENT
LEFT JOIN [dbo].[TB_M_SECTION] SEC ON SEC.SECTION_CODE = R.SECTION_CODE AND SEC.DEPARTMENT_CODE = DEP.DEPARTMENT_CODE
WHERE R.DIVISION_NAME IS NULL AND R.DEPARTMENT_NAME IS NULL AND R.SECTION_NAME IS NULL;

UPDATE R SET
	R.DIVISION_NAME = DIV.DIVISION_NAME,
	R.DEPARTMENT_CODE = DEP.DEPARTMENT_CODE,
	R.DEPARTMENT_NAME = DEP.DEPARTMENT_NAME,
	R.SECTION_NAME = SEC.SECTION_NAME
FROM [dbo].[TB_R_DOCUMENT_HISTORY] R
LEFT JOIN [dbo].[TB_M_DIVISION] DIV ON DIV.DIVISION_CODE = R.DIVISION
LEFT JOIN [dbo].[TB_M_DEPARTMENT] DEP ON DEP.DEPARTMENT_ID = R.DEPARTMENT
LEFT JOIN [dbo].[TB_M_SECTION] SEC ON SEC.SECTION_CODE = R.SECTION_CODE AND SEC.DEPARTMENT_CODE = DEP.DEPARTMENT_CODE
WHERE R.DIVISION_NAME IS NULL AND R.DEPARTMENT_NAME IS NULL AND R.SECTION_NAME IS NULL;

