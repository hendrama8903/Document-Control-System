-- =====================================================================
-- Snapshot nama Division/Department/Section ke tabel transaksi (request
-- Hendra 2026-08-22).
--
-- Masalah: DIVISION_NAME/DEPARTMENT_NAME/SECTION_NAME cuma tersimpan di
-- tabel master (TB_M_DIVISION/TB_M_DEPARTMENT/TB_M_SECTION). Semua tabel
-- transaksi cuma simpan kode/ID, nama diambil lewat JOIN live ke master
-- tiap kali ditampilkan/dicetak - jadi rename nama di Master otomatis
-- mengubah tampilan SEMUA dokumen lama (termasuk yang sudah dicetak/
-- diarsipkan). Division Code sendiri sudah readonly saat Edit, jadi aman
-- dipakai sebagai kunci; masalahnya murni di NAME.
--
-- Fix: tambah kolom snapshot di tabel transaksi, diisi SEKALI saat record
-- dibuat (lihat perubahan di masing-masing sp_..._Insert / SupersedeRevision/
-- dst di SQL/StoredProcedures/). SP baca (Search/GetByKey) diubah pakai
-- ISNULL(snapshot, live-join) supaya baris lama (snapshot masih NULL,
-- termasuk 3 baris dev existing) tetap tampil normal dari master sampai
-- direvisi/dibuat ulang.
--
-- Kolom sengaja diberi nama SAMA PERSIS dengan alias yang sudah dipakai SP
-- (DIVISION_NAME/DEPARTMENT_CODE/DEPARTMENT_NAME/SECTION_NAME) - properti
-- C# yang bersangkutan SUDAH ADA di model (bukan [NotMapped], dicek satu
-- per satu), jadi TIDAK ADA perubahan C#/View/export yang diperlukan sama
-- sekali. Lihat SQL/StoredProcedures/*.sql untuk perubahan baca/tulisnya.
--
-- Idempotent (guard pakai COL_LENGTH sebelum ADD COLUMN). Jalankan di
-- database DMS_NEW.
-- =====================================================================
