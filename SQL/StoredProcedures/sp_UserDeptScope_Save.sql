-- Replace the departments a PIC handles. @DEPARTMENT_IDS: comma separated IDs, empty = none.
-- The user's own position department is not stored (it is always allowed).
-- See SQL/DocumentDepartmentScope_Migration.sql (2026-11-17).
CREATE OR ALTER PROCEDURE [dbo].[sp_UserDeptScope_Save]
	@USERNAME       VARCHAR(50),
	@DEPARTMENT_IDS VARCHAR(MAX),
	@LOGIN_USER     VARCHAR(50)
AS
BEGIN
	SET NOCOUNT ON;
	SET XACT_ABORT ON;

	IF NOT EXISTS (SELECT 1 FROM dbo.TB_M_USER WHERE USERNAME = @USERNAME)
	BEGIN
		SELECT CAST(0 AS BIT) AS status, 'User ' + ISNULL(@USERNAME, '') + ' not found.' AS message;
		RETURN;
	END

	BEGIN TRANSACTION;
	DELETE FROM dbo.TB_M_USER_DEPT_SCOPE WHERE USERNAME = @USERNAME;

	INSERT dbo.TB_M_USER_DEPT_SCOPE (USERNAME, DEPARTMENT_ID, CREATED_BY, CREATED_DT)
	SELECT DISTINCT @USERNAME, D.DEPARTMENT_ID, @LOGIN_USER, GETDATE()
	FROM STRING_SPLIT(ISNULL(@DEPARTMENT_IDS, ''), ',') V
	JOIN dbo.TB_M_DEPARTMENT D ON D.DEPARTMENT_ID = TRY_CAST(LTRIM(RTRIM(V.value)) AS INT)
	WHERE ISNULL(D.DELETE_FLAG, 0) = 0
	  AND NOT EXISTS (SELECT 1 FROM dbo.TB_M_USER_POS P WHERE P.USERNAME = @USERNAME AND P.DEPARTMENT_ID = D.DEPARTMENT_ID);
	COMMIT TRANSACTION;

	SELECT CAST(1 AS BIT) AS status, 'Departments handled saved.' AS message;
END
GO
