-- Record one Download PDF from Document Control (see SQL/DocumentExportPdf_Migration.sql).
-- A CONTROLLED copy gets the next copy number of its document revision
-- (DOCUMENT_CODE + REVISION): 1, 2, 3, ... Locked so two QMS users exporting at the same
-- moment never get the same number. Returns EXPORT_ID and COPY_NO (NULL for other purposes).
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentExport_Insert]
	@DOCUMENT_TRANSACTION_ID  INT,
	@DOCUMENT_CODE            VARCHAR(255),
	@REVISION                 INT = NULL,
	@PURPOSE                  VARCHAR(20),
	@RECIPIENT                NVARCHAR(200) = NULL,
	@NOTES                    NVARCHAR(500) = NULL,
	@USERNAME                 VARCHAR(50)
AS
BEGIN
	SET NOCOUNT ON;
	SET XACT_ABORT ON;

	SET @RECIPIENT = NULLIF(LTRIM(RTRIM(@RECIPIENT)), '');
	SET @NOTES = NULLIF(LTRIM(RTRIM(@NOTES)), '');

	IF @PURPOSE NOT IN ('MASTER', 'CONTROLLED', 'UNCONTROLLED')
		THROW 50001, 'Unknown export purpose.', 1;
	IF @PURPOSE = 'CONTROLLED' AND @RECIPIENT IS NULL
		THROW 50002, 'A controlled copy needs a recipient.', 1;

	DECLARE @COPY_NO INT = NULL;

	BEGIN TRAN;

	IF @PURPOSE = 'CONTROLLED'
	BEGIN
		SELECT @COPY_NO = ISNULL(MAX(COPY_NO), 0) + 1
		FROM [dbo].[TB_R_DOCUMENT_EXPORT] WITH (UPDLOCK, HOLDLOCK)
		WHERE DOCUMENT_CODE = @DOCUMENT_CODE
		  AND ISNULL(REVISION, -1) = ISNULL(@REVISION, -1)
		  AND PURPOSE = 'CONTROLLED';
	END

	INSERT INTO [dbo].[TB_R_DOCUMENT_EXPORT]
		(DOCUMENT_TRANSACTION_ID, DOCUMENT_CODE, REVISION, PURPOSE, COPY_NO, RECIPIENT, NOTES, CREATED_BY, CREATED_DT)
	VALUES
		(@DOCUMENT_TRANSACTION_ID, @DOCUMENT_CODE, @REVISION, @PURPOSE, @COPY_NO, @RECIPIENT, @NOTES, @USERNAME, GETDATE());

	DECLARE @EXPORT_ID INT = SCOPE_IDENTITY();

	COMMIT TRAN;

	SELECT @EXPORT_ID AS EXPORT_ID, @COPY_NO AS COPY_NO;
END
GO
