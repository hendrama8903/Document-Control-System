-- Pencarian dokumen global (kotak "Search documents" di top bar, request Hendra
-- 2026-11-06). Mencocokkan SEMUA kata kunci (dipisah spasi, maks 6 kata) ke nomor,
-- judul, dan ISI dokumen (TB_R_DOCUMENT_CONTENT, lihat
-- SQL/DocumentFullTextSearch_Migration.sql). Kecocokan di nomor/judul diurutkan
-- lebih dulu.
--
-- Hak lihat dokumen internal:
--   - Admin (@IS_ADMIN = 1): semua dokumen yang tidak dihapus
--   - User lain: dokumen Approved / Published / Obsolete (1, 5, 4), ditambah dokumen
--     yang ia buat atau yang melewati approval-nya (draft, menunggu, ditolak)
-- Dokumen eksternal yang tidak dihapus terlihat oleh semua user.
-- 2026-11-10: hak lihat mengikuti dbo.fn_Document_CanView / fn_ExternalDocument_CanView
-- (role, menu, distribusi, divisi, Rahasia) - @IS_ADMIN tidak lagi dipakai.
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentSearch]
	@KEYWORD     NVARCHAR(200),
	@USERNAME    VARCHAR(50),
	@IS_ADMIN    BIT = 0,
	@PageNumber  INT = 1,
	@PageSize    INT = 20
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @TERMS TABLE (TERM NVARCHAR(100) PRIMARY KEY);
	INSERT INTO @TERMS (TERM)
	SELECT DISTINCT TOP 6 LTRIM(RTRIM(value))
	FROM STRING_SPLIT(REPLACE(REPLACE(ISNULL(@KEYWORD, ''), CHAR(9), ' '), CHAR(13), ' '), ' ')
	WHERE LEN(LTRIM(RTRIM(value))) >= 2;

	DECLARE @TERM_COUNT INT = (SELECT COUNT(*) FROM @TERMS);
	IF @TERM_COUNT = 0
	BEGIN
		SELECT TOP 0 CAST(NULL AS VARCHAR(10)) AS SOURCE_TYPE, CAST(NULL AS INT) AS SOURCE_ID, CAST(NULL AS INT) AS TOTAL_ROWS;
		RETURN;
	END

	DECLARE @FIRST NVARCHAR(100) = (SELECT TOP 1 TERM FROM @TERMS ORDER BY LEN(TERM) DESC);

	;WITH docs AS (
		SELECT 'INTERNAL' AS SOURCE_TYPE, D.DOCUMENT_TRANSACTION_ID AS SOURCE_ID, D.DOCUMENT_CODE,
			D.DOCUMENT_TRANSACTION_NAME AS TITLE, CAST(D.REVISION AS VARCHAR(50)) AS REVISION,
			D.[STATUS], ISNULL(S.SYSTEM_VALUE, D.[STATUS]) AS STATUS_NAME, D.DEPARTMENT_NAME,
			M.DOCUMENT_NAME AS CATEGORY_NAME, D.FILE_PATH, D.DOCUMENT_DATE AS DOC_DATE
		FROM dbo.TB_R_DOCUMENT D
		LEFT JOIN dbo.TB_M_DOCUMENT M ON M.DOCUMENT_ID = D.DOCUMENT_ID
		LEFT JOIN dbo.TB_M_SYSTEM S ON S.SYSTEM_TYPE = 'DOC_STATUS' AND S.SYSTEM_CODE = D.[STATUS]
		WHERE ISNULL(D.DELETE_FLAG, 0) = 0 AND ISNULL(D.[STATUS], '') <> '3'
		-- Hak lihat sama dengan ViewAttachment & My Documents (SQL/DocumentAccess_Migration.sql).
		AND dbo.fn_Document_CanView(@USERNAME, D.DOCUMENT_TRANSACTION_ID) = 1
		UNION ALL
		SELECT 'EXTERNAL', E.EXTERNAL_DOCUMENT_ID, NULL, E.DOCUMENT_NAME, E.REVISION_EDITION,
			E.[STATUS], ISNULL(S.SYSTEM_VALUE, E.[STATUS]), E.DEPARTMENT_NAME,
			'External Document', E.FILE_PATH, E.RECEIVED_DATE
		FROM dbo.TB_M_EXTERNAL_DOCUMENT E
		LEFT JOIN dbo.TB_M_SYSTEM S ON S.SYSTEM_TYPE = 'EXT_DOC_STATUS' AND S.SYSTEM_CODE = E.[STATUS]
		WHERE ISNULL(E.DELETE_FLAG, 0) = 0
		AND dbo.fn_ExternalDocument_CanView(@USERNAME) = 1
	),
	matched AS (
		SELECT d.*, C.CONTENT, C.INDEX_STATUS, C.EXTRACT_METHOD,
			CASE WHEN NOT EXISTS (
				SELECT 1 FROM @TERMS T
				WHERE CHARINDEX(T.TERM, ISNULL(d.DOCUMENT_CODE, '') + N' ' + ISNULL(d.TITLE, '')) = 0
			) THEN 1 ELSE 0 END AS MATCH_IN_TITLE
		FROM docs d
		LEFT JOIN dbo.TB_R_DOCUMENT_CONTENT C ON C.SOURCE_TYPE = d.SOURCE_TYPE AND C.SOURCE_ID = d.SOURCE_ID
		WHERE NOT EXISTS (
			SELECT 1 FROM @TERMS T
			WHERE CHARINDEX(T.TERM, ISNULL(d.DOCUMENT_CODE, '') + N' ' + ISNULL(d.TITLE, '')) = 0
			  AND CHARINDEX(T.TERM, ISNULL(C.CONTENT, N'')) = 0
		)
	),
	ranked AS (
		SELECT m.*,
			ROW_NUMBER() OVER (ORDER BY m.MATCH_IN_TITLE DESC,
				CASE WHEN m.[STATUS] IN ('1', '5') OR (m.SOURCE_TYPE = 'EXTERNAL' AND m.[STATUS] = '1') THEN 0 ELSE 1 END,
				m.DOC_DATE DESC, m.SOURCE_ID DESC) AS ROW_NUM,
			COUNT(*) OVER () AS TOTAL_ROWS
		FROM matched m
	)
	SELECT
		r.SOURCE_TYPE, r.SOURCE_ID, r.DOCUMENT_CODE, r.TITLE, r.REVISION, r.[STATUS], r.STATUS_NAME,
		r.DEPARTMENT_NAME, r.CATEGORY_NAME, r.FILE_PATH, r.DOC_DATE, r.MATCH_IN_TITLE, r.INDEX_STATUS, r.EXTRACT_METHOD,
		-- Cuplikan isi di sekitar kata kunci (kosong kalau hanya cocok di nomor/judul)
		CASE WHEN CHARINDEX(@FIRST, ISNULL(r.CONTENT, N'')) > 0 THEN
			SUBSTRING(r.CONTENT, CASE WHEN CHARINDEX(@FIRST, r.CONTENT) > 90 THEN CHARINDEX(@FIRST, r.CONTENT) - 90 ELSE 1 END, 240)
		ELSE (SELECT TOP 1 SUBSTRING(r.CONTENT, CASE WHEN CHARINDEX(T.TERM, r.CONTENT) > 90 THEN CHARINDEX(T.TERM, r.CONTENT) - 90 ELSE 1 END, 240)
		      FROM @TERMS T WHERE CHARINDEX(T.TERM, ISNULL(r.CONTENT, N'')) > 0)
		END AS SNIPPET,
		r.TOTAL_ROWS
	FROM ranked r
	WHERE r.ROW_NUM > @PageSize * (@PageNumber - 1) AND r.ROW_NUM <= @PageSize * @PageNumber
	ORDER BY r.ROW_NUM;
END
GO
