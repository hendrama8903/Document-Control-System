-- What a binder holds (Binder Index, 2026-11-15, SQL/DocumentBinder_Migration.sql).
--   Controlled copy binder: the numbered copies in circulation filed in it. IS_OBSOLETE = the
--     copy belongs to a superseded revision and must be withdrawn and replaced by
--     CURRENT_REVISION (NULL when the document itself is no longer effective).
--   Master binder / plain folder: the effective documents assigned to it.
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentBinder_Contents]
	@FOLDER_ID  INT
AS
BEGIN
	SET NOCOUNT ON;

	IF EXISTS (SELECT 1 FROM [dbo].[TB_M_DOCUMENT_FOLDER] WHERE FOLDER_ID = @FOLDER_ID AND FOLDER_TYPE = 'COPY')
	BEGIN
		SELECT
			E.EXPORT_ID,
			E.DOCUMENT_TRANSACTION_ID,
			E.DOCUMENT_CODE,
			CUR.DOCUMENT_TRANSACTION_NAME AS DOCUMENT_NAME,
			E.REVISION,
			CUR.REVISION AS CURRENT_REVISION,
			E.COPY_NO,
			E.RECIPIENT,
			E.CREATED_DT AS ISSUED_DT,
			CAST(CASE WHEN EXISTS (SELECT 1 FROM [dbo].[TB_R_DOCUMENT] D WHERE D.DOCUMENT_TRANSACTION_ID = E.DOCUMENT_TRANSACTION_ID)
			          THEN 0 ELSE 1 END AS BIT) AS IS_OBSOLETE
		FROM [dbo].[TB_R_DOCUMENT_EXPORT] E
		OUTER APPLY (
			SELECT TOP 1 D.REVISION, D.DOCUMENT_TRANSACTION_NAME
			FROM [dbo].[TB_R_DOCUMENT] D
			-- the current revision, also when the document got a new number since (2026-11-19)
			WHERE D.DOCUMENT_CODE = dbo.fn_Document_LatestCode(E.DOCUMENT_CODE) AND D.STATUS IN ('1', '5') AND ISNULL(D.DELETE_FLAG, 0) = 0
			ORDER BY D.REVISION DESC
		) CUR
		WHERE E.FOLDER_ID = @FOLDER_ID AND E.PURPOSE = 'CONTROLLED' AND E.WITHDRAWN_DT IS NULL
		ORDER BY E.DOCUMENT_CODE, E.REVISION, E.COPY_NO;
		RETURN;
	END

	SELECT
		CAST(NULL AS INT) AS EXPORT_ID,
		D.DOCUMENT_TRANSACTION_ID,
		D.DOCUMENT_CODE,
		D.DOCUMENT_TRANSACTION_NAME AS DOCUMENT_NAME,
		D.REVISION,
		D.REVISION AS CURRENT_REVISION,
		CAST(NULL AS INT) AS COPY_NO,
		CAST(NULL AS NVARCHAR(200)) AS RECIPIENT,
		D.DOCUMENT_DATE AS ISSUED_DT,
		CAST(0 AS BIT) AS IS_OBSOLETE
	FROM [dbo].[TB_R_DOCUMENT] D
	WHERE D.FOLDER_ID = @FOLDER_ID AND D.STATUS IN ('1', '5') AND ISNULL(D.DELETE_FLAG, 0) = 0
	ORDER BY D.DOCUMENT_CODE;
END
GO
