-- Pratinjau approval chain sebelum dokumen disimpan (Document Preparation).
-- Memakai fungsi yang sama dengan sp_WorkflowDoc_Create, jadi hasilnya sama
-- persis dengan chain yang nanti benar-benar dibuat (request Hendra 2026-11-06).
--
-- Satu baris per langkah alur. STATUS:
--   OK          - approver ditemukan (APPROVER terisi)
--   AUTO        - langkah pertama yang approvernya pembuat sendiri (langsung approve)
--   SKIP        - tidak ada user di cakupan jabatan itu, langkah tidak wajib -> dilewati
--   MISSING     - sama, tetapi langkah WAJIB -> dokumen tidak bisa disimpan
-- Kalau pembuat/alur tidak ditemukan: satu baris STATUS = NO_CREATOR / NO_WORKFLOW.
CREATE OR ALTER PROCEDURE [dbo].[sp_WorkflowDoc_Preview]
	@DOCUMENT_LEVEL 	INT,
	@DOCUMENT_ID			INT,
	@DOCUMENT_CREATOR VARCHAR(50)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @CREATOR_LEVEL INT, @CREATOR_POSITION VARCHAR(255),
					@WORKFLOW_DOC_ID INT, @IS_CATEGORY_WORKFLOW BIT;

	SELECT @CREATOR_LEVEL = POSITION_LEVEL, @CREATOR_POSITION = POSITION_NAME
	FROM dbo.fn_WorkflowDoc_Creator(@DOCUMENT_CREATOR);

	IF @CREATOR_LEVEL IS NULL
	BEGIN
		SELECT 'NO_CREATOR' AS STATUS, CAST(NULL AS VARCHAR(255)) AS CREATOR_POSITION, CAST(0 AS BIT) AS IS_CATEGORY_WORKFLOW,
			CAST(NULL AS INT) AS WORKFLOW_SEQ, CAST(NULL AS INT) AS ACTUAL_SEQ, CAST(NULL AS INT) AS POSITION_ID,
			CAST(NULL AS VARCHAR(255)) AS POSITION_NAME, CAST(NULL AS VARCHAR(255)) AS LABEL, CAST(0 AS BIT) AS IS_MANDATORY,
			CAST(NULL AS VARCHAR(50)) AS APPROVER, CAST(NULL AS VARCHAR(255)) AS APPROVER_NAME;
		RETURN;
	END

	SELECT @WORKFLOW_DOC_ID = WORKFLOW_DOC_ID, @IS_CATEGORY_WORKFLOW = IS_CATEGORY_WORKFLOW
	FROM dbo.fn_WorkflowDoc_FindHeader(@DOCUMENT_LEVEL, @DOCUMENT_ID, @CREATOR_LEVEL);

	IF @WORKFLOW_DOC_ID IS NULL
	BEGIN
		SELECT 'NO_WORKFLOW' AS STATUS, @CREATOR_POSITION AS CREATOR_POSITION, CAST(0 AS BIT) AS IS_CATEGORY_WORKFLOW,
			CAST(NULL AS INT) AS WORKFLOW_SEQ, CAST(NULL AS INT) AS ACTUAL_SEQ, CAST(NULL AS INT) AS POSITION_ID,
			CAST(NULL AS VARCHAR(255)) AS POSITION_NAME, CAST(NULL AS VARCHAR(255)) AS LABEL, CAST(0 AS BIT) AS IS_MANDATORY,
			CAST(NULL AS VARCHAR(50)) AS APPROVER, CAST(NULL AS VARCHAR(255)) AS APPROVER_NAME;
		RETURN;
	END

	;WITH S AS (
		SELECT *,
			CASE WHEN APPROVER IS NULL THEN NULL
				 ELSE ROW_NUMBER() OVER (PARTITION BY CASE WHEN APPROVER IS NULL THEN 0 ELSE 1 END ORDER BY WORKFLOW_SEQ) END AS ACTUAL_SEQ
		FROM dbo.fn_WorkflowDoc_Steps(@WORKFLOW_DOC_ID, @DOCUMENT_CREATOR)
	)
	SELECT
		CASE
			WHEN S.APPROVER IS NULL AND S.IS_MANDATORY = 1 THEN 'MISSING'
			WHEN S.APPROVER IS NULL THEN 'SKIP'
			WHEN S.ACTUAL_SEQ = 1 AND S.APPROVER = @DOCUMENT_CREATOR THEN 'AUTO'
			ELSE 'OK'
		END AS STATUS,
		@CREATOR_POSITION AS CREATOR_POSITION,
		@IS_CATEGORY_WORKFLOW AS IS_CATEGORY_WORKFLOW,
		S.WORKFLOW_SEQ,
		CAST(S.ACTUAL_SEQ AS INT) AS ACTUAL_SEQ,
		S.POSITION_ID,
		S.POSITION_NAME,
		S.LABEL,
		S.IS_MANDATORY,
		S.APPROVER,
		U.FULL_NAME AS APPROVER_NAME
	FROM S
	LEFT JOIN dbo.TB_M_USER U ON U.USERNAME = S.APPROVER
	ORDER BY S.WORKFLOW_SEQ;
END
GO
