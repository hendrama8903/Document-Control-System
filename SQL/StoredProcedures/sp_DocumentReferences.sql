-- Analisis dampak revisi (OCR tahap 2, request Hendra 2026-11-06): dokumen lain yang
-- MENYEBUT nomor dokumen @DOCUMENT_CODE di judul atau isinya (TB_R_DOCUMENT_CONTENT,
-- termasuk teks hasil OCR dokumen scan). Ditampilkan saat membuat revisi, supaya
-- pembuat & QMS tahu dokumen mana yang mungkin ikut perlu ditinjau.
--
-- Dokumen internal: hanya revisi TERAKHIR yang berlaku (Approved / Published) per
-- nomor dokumen, selain dokumen itu sendiri. Dokumen eksternal: yang tidak dihapus.
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentReferences]
	@DOCUMENT_CODE VARCHAR(255)
AS
BEGIN
	SET NOCOUNT ON;
	SET @DOCUMENT_CODE = NULLIF(LTRIM(RTRIM(@DOCUMENT_CODE)), '');
	IF @DOCUMENT_CODE IS NULL OR LEN(@DOCUMENT_CODE) < 4 RETURN;

	;WITH latest AS (
		SELECT D.*, ROW_NUMBER() OVER (PARTITION BY D.DOCUMENT_CODE ORDER BY D.REVISION DESC, D.DOCUMENT_TRANSACTION_ID DESC) AS RN
		FROM dbo.TB_R_DOCUMENT D
		WHERE ISNULL(D.DELETE_FLAG, 0) = 0 AND D.[STATUS] IN ('1', '5')
		AND D.DOCUMENT_CODE <> @DOCUMENT_CODE
	),
	docs AS (
		SELECT 'INTERNAL' AS SOURCE_TYPE, L.DOCUMENT_TRANSACTION_ID AS SOURCE_ID, L.DOCUMENT_CODE,
			L.DOCUMENT_TRANSACTION_NAME AS TITLE, CAST(L.REVISION AS VARCHAR(50)) AS REVISION,
			ISNULL(S.SYSTEM_VALUE, L.[STATUS]) AS STATUS_NAME, L.DEPARTMENT_NAME, L.FILE_PATH
		FROM latest L
		LEFT JOIN dbo.TB_M_SYSTEM S ON S.SYSTEM_TYPE = 'DOC_STATUS' AND S.SYSTEM_CODE = L.[STATUS]
		WHERE L.RN = 1
		UNION ALL
		SELECT 'EXTERNAL', E.EXTERNAL_DOCUMENT_ID, NULL, E.DOCUMENT_NAME, E.REVISION_EDITION,
			ISNULL(S.SYSTEM_VALUE, E.[STATUS]), E.DEPARTMENT_NAME, E.FILE_PATH
		FROM dbo.TB_M_EXTERNAL_DOCUMENT E
		LEFT JOIN dbo.TB_M_SYSTEM S ON S.SYSTEM_TYPE = 'EXT_DOC_STATUS' AND S.SYSTEM_CODE = E.[STATUS]
		WHERE ISNULL(E.DELETE_FLAG, 0) = 0
	)
	SELECT d.SOURCE_TYPE, d.SOURCE_ID, d.DOCUMENT_CODE, d.TITLE, d.REVISION, d.STATUS_NAME, d.DEPARTMENT_NAME, d.FILE_PATH,
		C.EXTRACT_METHOD,
		CAST(CASE WHEN CHARINDEX(@DOCUMENT_CODE, ISNULL(d.TITLE, '')) > 0 THEN 1 ELSE 0 END AS BIT) AS IN_TITLE,
		CASE WHEN CHARINDEX(@DOCUMENT_CODE, ISNULL(C.CONTENT, N'')) > 0 THEN
			SUBSTRING(C.CONTENT, CASE WHEN CHARINDEX(@DOCUMENT_CODE, C.CONTENT) > 80 THEN CHARINDEX(@DOCUMENT_CODE, C.CONTENT) - 80 ELSE 1 END, 220)
		END AS SNIPPET
	FROM docs d
	LEFT JOIN dbo.TB_R_DOCUMENT_CONTENT C ON C.SOURCE_TYPE = d.SOURCE_TYPE AND C.SOURCE_ID = d.SOURCE_ID
	WHERE CHARINDEX(@DOCUMENT_CODE, ISNULL(d.TITLE, '')) > 0
	   OR CHARINDEX(@DOCUMENT_CODE, ISNULL(C.CONTENT, N'')) > 0
	ORDER BY d.SOURCE_TYPE DESC, d.DOCUMENT_CODE, d.TITLE;
END
GO
