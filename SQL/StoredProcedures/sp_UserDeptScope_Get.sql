-- Departments a PIC handles besides their own (User Position > Departments Handled).
-- See SQL/DocumentDepartmentScope_Migration.sql (2026-11-17).
CREATE OR ALTER PROCEDURE [dbo].[sp_UserDeptScope_Get]
	@USERNAME VARCHAR(50)
AS
BEGIN
	SET NOCOUNT ON;
	SELECT D.DEPARTMENT_ID, D.DEPARTMENT_CODE, D.DEPARTMENT_NAME, D.DIVISION
	FROM dbo.TB_M_USER_DEPT_SCOPE S
	JOIN dbo.TB_M_DEPARTMENT D ON D.DEPARTMENT_ID = S.DEPARTMENT_ID
	WHERE S.USERNAME = @USERNAME AND ISNULL(D.DELETE_FLAG, 0) <> 2
	ORDER BY D.DIVISION, D.DEPARTMENT_CODE;
END
GO
