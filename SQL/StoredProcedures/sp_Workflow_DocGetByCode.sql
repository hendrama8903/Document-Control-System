-- IS_MANDATORY (langkah wajib) - wajib lengkap karena dibaca lewat
-- FromSqlRaw<WorkflowDoc>.
CREATE OR ALTER PROCEDURE [dbo].[sp_Workflow_DocGetByCode]
	@WORKFLOW_DOC_ID  	int,
	@DOCUMENT_LEVEL     int
AS
BEGIN
	SET NOCOUNT ON;

	SELECT
		CAST(W.WORKFLOW_DOC_ID AS INT) AS WORKFLOW_DOC_ID,
		H.DOCUMENT_LEVEL,
		H.CREATOR_LEVEL,
		H.DOCUMENT_ID,
		H.IS_ACTIVE,
		CAST(W.WORKFLOW_SEQ AS INT) AS WORKFLOW_SEQ,
		W.POSITION_ID,
		U.POSITION_NAME,
		W.LABEL,
		W.IS_MANDATORY,
		W.CREATED_DT,
		W.CREATED_BY,
		W.CHANGED_DT,
		W.CHANGED_BY
	FROM [dbo].[TB_M_WORKFLOW_DOC_D] W
	JOIN [dbo].[TB_M_WORKFLOW_DOC_H] H ON H.WORKFLOW_DOC_ID = W.WORKFLOW_DOC_ID
	JOIN [dbo].[TB_M_POSITION] U ON W.POSITION_ID = U.POSITION_ID
	WHERE (@WORKFLOW_DOC_ID IS NULL OR H.WORKFLOW_DOC_ID = @WORKFLOW_DOC_ID)
	AND (@DOCUMENT_LEVEL IS NULL OR H.DOCUMENT_LEVEL = @DOCUMENT_LEVEL)
	ORDER BY W.WORKFLOW_SEQ ASC;
END
GO
