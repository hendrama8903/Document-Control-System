-- Access Rights Review: satu baris per user dengan role, jabatan, jumlah menu
-- dan fungsi dari role-nya, serta aktivitas login (TB_R_USER_LOGIN_LOG).
-- @STATUS: NULL = semua, 'ACTIVE', 'INACTIVE' (DELETE_FLAG = '1').
CREATE OR ALTER PROCEDURE [dbo].[sp_AccessRight_Users]
	@ROLE_ID  VARCHAR(50) = NULL,
	@STATUS   VARCHAR(10) = NULL,
	@KEYWORD  VARCHAR(255) = NULL
AS
BEGIN
	SET NOCOUNT ON;

	;WITH MENU_CNT AS (
		SELECT A.ROLE_ID, COUNT(*) AS MENU_COUNT
		FROM dbo.TB_M_AUTH_MENU A
		JOIN dbo.TB_M_MENU M ON M.MENU_ID = A.MENU_ID
		LEFT JOIN dbo.TB_M_MENU P ON P.MENU_ID = M.PARENT_ID
		WHERE ISNULL(M.DELETE_FLAG, 0) = 0 AND ISNULL(P.DELETE_FLAG, 0) = 0
		  AND ISNULL(M.MENU_URL, '#') <> '#'
		GROUP BY A.ROLE_ID
	), FUNC_CNT AS (
		SELECT A.ROLE_ID, COUNT(*) AS FUNCTION_COUNT
		FROM dbo.TB_M_AUTH_FUNCTION A
		JOIN dbo.TB_M_FUNCTION F ON F.FUNCTION_ID = A.FUNCTION_ID
		LEFT JOIN dbo.TB_M_MENU M ON M.MENU_ID = F.MENU_ID
		WHERE ISNULL(F.DELETE_FLAG, 0) = 0 AND ISNULL(M.DELETE_FLAG, 0) = 0
		GROUP BY A.ROLE_ID
	), POS AS (
		SELECT UP.USERNAME,
			STRING_AGG(CONVERT(VARCHAR(MAX),
				ISNULL(PO.POSITION_NAME, '-') + ' - ' +
				COALESCE(S.SECTION_NAME, D.DEPARTMENT_NAME, DV.DIVISION_NAME, UP.DIVISION, '-')), '; ') AS POSITIONS,
			STRING_AGG(CONVERT(VARCHAR(MAX), ISNULL(DV.DIVISION_NAME, UP.DIVISION)), '; ') AS DIVISIONS,
			STRING_AGG(CONVERT(VARCHAR(MAX), D.DEPARTMENT_NAME), '; ') AS DEPARTMENTS
		FROM dbo.TB_M_USER_POS UP
		LEFT JOIN dbo.TB_M_POSITION PO ON PO.POSITION_ID = UP.POSITION_ID
		LEFT JOIN dbo.TB_M_DIVISION DV ON DV.DIVISION_CODE = UP.DIVISION
		LEFT JOIN dbo.TB_M_DEPARTMENT D ON D.DEPARTMENT_ID = UP.DEPARTMENT_ID
		LEFT JOIN dbo.TB_M_SECTION S ON S.SECTION_ID = UP.SECTION_ID
		GROUP BY UP.USERNAME
	), LOGIN AS (
		SELECT USERNAME,
			MAX(CASE WHEN RESULT = 'SUCCESS' THEN LOGIN_DT END) AS LAST_LOGIN_DT,
			SUM(CASE WHEN RESULT = 'SUCCESS' AND LOGIN_DT >= DATEADD(DAY, -90, GETDATE()) THEN 1 ELSE 0 END) AS LOGIN_COUNT_90D,
			SUM(CASE WHEN RESULT = 'FAILED' AND LOGIN_DT >= DATEADD(DAY, -30, GETDATE()) THEN 1 ELSE 0 END) AS FAILED_LOGIN_30D,
			MAX(CASE WHEN RESULT = 'FAILED' THEN LOGIN_DT END) AS LAST_FAILED_DT
		FROM dbo.TB_R_USER_LOGIN_LOG
		GROUP BY USERNAME
	)
	SELECT
		U.USERNAME,
		U.FULL_NAME,
		U.REG_NO,
		U.EMAIL,
		U.ROLE_ID,
		R.ROLE_NAME,
		CASE WHEN U.AD_USER = '1' THEN 'Active Directory' ELSE 'Local' END AS ACCOUNT_TYPE,
		CASE WHEN ISNULL(U.DELETE_FLAG, '0') = '1' THEN 0 ELSE 1 END AS IS_ACTIVE,
		POS.POSITIONS,
		POS.DIVISIONS,
		POS.DEPARTMENTS,
		ISNULL(MC.MENU_COUNT, 0) AS MENU_COUNT,
		ISNULL(FC.FUNCTION_COUNT, 0) AS FUNCTION_COUNT,
		L.LAST_LOGIN_DT,
		ISNULL(L.LOGIN_COUNT_90D, 0) AS LOGIN_COUNT_90D,
		ISNULL(L.FAILED_LOGIN_30D, 0) AS FAILED_LOGIN_30D,
		L.LAST_FAILED_DT,
		U.CREATED_BY,
		U.CREATED_DT,
		U.CHANGED_BY,
		U.CHANGED_DT
	FROM dbo.TB_M_USER U
	LEFT JOIN dbo.TB_M_ROLE R ON R.ROLE_ID = U.ROLE_ID
	LEFT JOIN MENU_CNT MC ON MC.ROLE_ID = U.ROLE_ID
	LEFT JOIN FUNC_CNT FC ON FC.ROLE_ID = U.ROLE_ID
	LEFT JOIN POS ON POS.USERNAME = U.USERNAME
	LEFT JOIN LOGIN L ON L.USERNAME = U.USERNAME
	WHERE (@ROLE_ID IS NULL OR U.ROLE_ID = @ROLE_ID)
	  AND (@STATUS IS NULL
	       OR (@STATUS = 'ACTIVE' AND ISNULL(U.DELETE_FLAG, '0') <> '1')
	       OR (@STATUS = 'INACTIVE' AND ISNULL(U.DELETE_FLAG, '0') = '1'))
	  AND (@KEYWORD IS NULL
	       OR U.USERNAME LIKE '%' + @KEYWORD + '%'
	       OR U.FULL_NAME LIKE '%' + @KEYWORD + '%'
	       OR U.REG_NO LIKE '%' + @KEYWORD + '%'
	       OR POS.DEPARTMENTS LIKE '%' + @KEYWORD + '%'
	       OR POS.DIVISIONS LIKE '%' + @KEYWORD + '%')
	ORDER BY CASE WHEN ISNULL(U.DELETE_FLAG, '0') = '1' THEN 1 ELSE 0 END, U.USERNAME;
END
GO
