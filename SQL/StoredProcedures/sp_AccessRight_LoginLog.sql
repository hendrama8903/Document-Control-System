-- Access Rights Review: riwayat login (berhasil/gagal) per periode / user.
CREATE OR ALTER PROCEDURE [dbo].[sp_AccessRight_LoginLog]
	@START_DT  DATE = NULL,
	@END_DT    DATE = NULL,
	@USERNAME  VARCHAR(255) = NULL
AS
BEGIN
	SET NOCOUNT ON;
	SELECT L.LOGIN_LOG_ID, L.LOGIN_DT, L.USERNAME, U.FULL_NAME, L.RESULT, L.MESSAGE, L.CLIENT_IP, L.USER_AGENT
	FROM dbo.TB_R_USER_LOGIN_LOG L
	LEFT JOIN dbo.TB_M_USER U ON U.USERNAME = L.USERNAME
	WHERE (@START_DT IS NULL OR L.LOGIN_DT >= @START_DT)
	  AND (@END_DT IS NULL OR L.LOGIN_DT < DATEADD(DAY, 1, @END_DT))
	  AND (@USERNAME IS NULL OR L.USERNAME = @USERNAME)
	ORDER BY L.LOGIN_DT DESC;
END
GO
