-- ============================================================
-- Part 2: New SP for inserting legacy revision-history rows directly into
-- TB_R_DOCUMENT_HISTORY (no matching active TB_R_DOCUMENT row/transaction ever
-- existed for these - they're historical revisions carried over from the paper
-- master list). Mirrors sp_DocumentMaintenance_ImportLegacyInsert's shape/logging,
-- but targets the history table with STATUS='4' (OBSOLETE) per the convention in
-- sp_DocumentMaintenance_SupersedeRevision.
-- ============================================================
SET ANSI_NULLS ON
GO
SET QUOTED_IDENTIFIER ON
GO
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentMaintenance_ImportLegacyHistoryInsert]
	@DOCUMENT_CODE				VARCHAR(25),
	@DOCUMENT_TRANSACTION_NAME	VARCHAR(255),
	@DOCUMENT_ID				INT,
	@LEVEL_CODE					INT,
	@DIVISION					VARCHAR(255),
	@DEPARTMENT					INT,
	@CLASSIFIED					INT,
	@REVISION					INT,
	@DOCUMENT_DATE				DATETIME,
	@FILE_PATH					VARCHAR(255),
	@DOCUMENT_CREATOR			VARCHAR(255),
	@REASON						VARCHAR(255),
	@CREATED_BY					VARCHAR(50),
	@RETURN_MSG					VARCHAR(MAX) OUTPUT,
	-- Management System (QMS / K3L / SMK3 / EMS, 2026-11-19). NULL = QMS. Archived systems are
	-- allowed here: an import brings old documents.
	@MGMT_SYSTEM				VARCHAR(10) = NULL
AS
BEGIN TRY
	DECLARE @PROCESS_ID BIGINT
	, @LOCATION VARCHAR(255) = 'sp_DocumentMaintenance_ImportLegacyHistoryInsert'

	EXEC sp_StartLog @PROCESS_ID OUTPUT, 'Document Maintenance', 'Import Legacy History Insert', @LOCATION, @CREATED_BY

	-- Snapshot nama Division/Department (request Hendra 2026-08-22), lihat
	-- SQL/OrgMasterData_NameSnapshot_Migration.sql.
	DECLARE @snap_DIVISION_NAME VARCHAR(255), @snap_DEPARTMENT_CODE VARCHAR(5), @snap_DEPARTMENT_NAME VARCHAR(255);

	SELECT @snap_DIVISION_NAME = DIVISION_NAME FROM TB_M_DIVISION WHERE DIVISION_CODE = @DIVISION;
	SELECT @snap_DEPARTMENT_CODE = DEPARTMENT_CODE, @snap_DEPARTMENT_NAME = DEPARTMENT_NAME FROM TB_M_DEPARTMENT WHERE DEPARTMENT_ID = @DEPARTMENT;

	-- Section from the code (2026-11-12), same rule as sp_DocumentMaintenance_ImportLegacyInsert:
	-- "ITD/SOP-APP-00/001" -> "00". The DOC_NO counter is raised there, not here,
	-- because every history row's code also has an active row.
	DECLARE @lastSlash INT = CHARINDEX('/', REVERSE(@DOCUMENT_CODE)),
			@seqPrefix VARCHAR(25), @SECTION_CODE VARCHAR(50), @snap_SECTION_NAME VARCHAR(255);

	IF @lastSlash > 1
		SET @seqPrefix = LEFT(@DOCUMENT_CODE, LEN(@DOCUMENT_CODE) - @lastSlash);

	IF @LEVEL_CODE IN (3, 4) AND @seqPrefix IS NOT NULL AND CHARINDEX('-', @seqPrefix) > 0
	BEGIN
		SET @SECTION_CODE = RIGHT(@seqPrefix, CHARINDEX('-', REVERSE(@seqPrefix)) - 1);
		SELECT @snap_SECTION_NAME = SECTION_NAME FROM TB_M_SECTION
		WHERE SECTION_CODE = @SECTION_CODE AND DEPARTMENT_CODE = @snap_DEPARTMENT_CODE;
	END

	-- Level 1/2: company and process from the code, same rule as ImportLegacyInsert.
	DECLARE @COMPANY_CODE VARCHAR(50), @PROCESS_CODE VARCHAR(50);
	IF @LEVEL_CODE IN (1, 2) AND CHARINDEX('/', @DOCUMENT_CODE) > 1
	BEGIN
		SELECT @COMPANY_CODE = SYSTEM_CODE FROM TB_M_SYSTEM
		WHERE SYSTEM_TYPE = 'COMPANY_CODE' AND SYSTEM_CODE = LEFT(@DOCUMENT_CODE, CHARINDEX('/', @DOCUMENT_CODE) - 1);
		IF @LEVEL_CODE = 2 AND CHARINDEX('/', @seqPrefix) > 0
			SELECT @PROCESS_CODE = SYSTEM_CODE FROM TB_M_SYSTEM
			WHERE SYSTEM_TYPE = 'PROCESS_CODE' AND SYSTEM_CODE = RIGHT(@seqPrefix, CHARINDEX('/', REVERSE(@seqPrefix)) - 1);
	END

	INSERT INTO [dbo].[TB_R_DOCUMENT_HISTORY]
		(DOCUMENT_TRANSACTION_ID, DOCUMENT_CODE, DOCUMENT_TRANSACTION_NAME, DOCUMENT_ID, LEVEL_CODE, DIVISION, DIVISION_NAME, DEPARTMENT, DEPARTMENT_CODE, DEPARTMENT_NAME,
		 SECTION_CODE, SECTION_NAME, COMPANY_CODE, PROCESS_CODE, DOCUMENT_TYPE, EXTERNAL_FLAG,
		 CLASSIFIED, REVISION, DOCUMENT_DATE, FILE_PATH, DOCUMENT_CREATOR, REASON, SOURCE,
		 STATUS, APPROVAL_ID,
		 CREATED_BY, CREATED_DT, CHANGED_BY, CHANGED_DT, MGMT_SYSTEM)
	VALUES
		(NULL, @DOCUMENT_CODE, @DOCUMENT_TRANSACTION_NAME, @DOCUMENT_ID, @LEVEL_CODE, @DIVISION, @snap_DIVISION_NAME, @DEPARTMENT, @snap_DEPARTMENT_CODE, @snap_DEPARTMENT_NAME,
		 @SECTION_CODE, @snap_SECTION_NAME, @COMPANY_CODE, @PROCESS_CODE, IIF(@REVISION > 0, '02', '01'), '0',
		 @CLASSIFIED, @REVISION, @DOCUMENT_DATE, @FILE_PATH, @DOCUMENT_CREATOR, @REASON, 'MIGRATION',
		 '4', NULL,
		 @CREATED_BY, GETDATE(), @CREATED_BY, GETDATE(), ISNULL(NULLIF(@MGMT_SYSTEM, ''), 'QMS'))

	SET @RETURN_MSG = 'Successfully Save Data'
	EXEC sp_WriteLog @PROCESS_ID, '2', 'INF', @RETURN_MSG, @LOCATION, @CREATED_BY
	RETURN 1;
END TRY
BEGIN CATCH
	SET @RETURN_MSG = 'ERROR: ' + ERROR_PROCEDURE() +': '+ ERROR_MESSAGE() + ', at line = ' +  CAST(ERROR_LINE() AS VARCHAR);
	EXEC sp_WriteLog @PROCESS_ID, '4', 'ERR', @RETURN_MSG, @LOCATION, @CREATED_BY
	RETURN 0;
END CATCH
GO
