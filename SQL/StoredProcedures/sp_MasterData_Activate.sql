-- Mengaktifkan lagi data master yang dinonaktifkan. Request Hendra 2026-11-07.
-- Ditolak kalau sudah ada data aktif dengan kode yang sama, atau induknya
-- (Division untuk Department, Department untuk Section) masih nonaktif. Induk yang
-- sudah tidak ada di tabel tidak menghalangi: 15 Department lama seperti itu.
CREATE OR ALTER PROCEDURE [dbo].[sp_MasterData_Activate]
	@ENTITY			VARCHAR(20),
	@ID				INT,
	@LOGIN_USER		VARCHAR(255),
	@RETURN_MSG		VARCHAR(MAX) OUTPUT
AS
BEGIN TRY
	SET NOCOUNT ON;

	DECLARE @PROCESS_ID BIGINT,
			@LOCATION VARCHAR(255) = 'sp_MasterData_Activate',
			@CODE VARCHAR(255),
			@PARENT VARCHAR(255);

	EXEC sp_StartLog @PROCESS_ID OUTPUT, 'Master Data', 'Activate', @LOCATION, @LOGIN_USER;

	IF @ENTITY = 'DEPARTMENT'
	BEGIN
		SELECT @CODE = DEPARTMENT_CODE, @PARENT = DIVISION FROM dbo.TB_M_DEPARTMENT WHERE DEPARTMENT_ID = @ID;
		IF EXISTS (SELECT 1 FROM dbo.TB_M_DEPARTMENT WHERE DEPARTMENT_CODE = @CODE AND ISNULL(DELETE_FLAG, 0) = 0 AND DEPARTMENT_ID <> @ID)
			SET @RETURN_MSG = 'ERROR: An active Department already uses code ' + @CODE + '.';
		ELSE IF EXISTS (SELECT 1 FROM dbo.TB_M_DIVISION WHERE DIVISION_CODE = @PARENT) AND NOT EXISTS (SELECT 1 FROM dbo.TB_M_DIVISION WHERE DIVISION_CODE = @PARENT AND ISNULL(DELETE_FLAG, 0) = 0)
			SET @RETURN_MSG = 'ERROR: Activate Division ' + ISNULL(@PARENT, '-') + ' before Department ' + @CODE + '.';
		ELSE
			UPDATE dbo.TB_M_DEPARTMENT SET DELETE_FLAG = 0, CHANGED_DT = GETDATE(), CHANGED_BY = @LOGIN_USER WHERE DEPARTMENT_ID = @ID;
	END
	ELSE IF @ENTITY = 'DIVISION'
	BEGIN
		SELECT @CODE = DIVISION_CODE FROM dbo.TB_M_DIVISION WHERE DIVISION_ID = @ID;
		IF EXISTS (SELECT 1 FROM dbo.TB_M_DIVISION WHERE DIVISION_CODE = @CODE AND ISNULL(DELETE_FLAG, 0) = 0 AND DIVISION_ID <> @ID)
			SET @RETURN_MSG = 'ERROR: An active Division already uses code ' + @CODE + '.';
		ELSE
			UPDATE dbo.TB_M_DIVISION SET DELETE_FLAG = 0, CHANGED_DT = GETDATE(), CHANGED_BY = @LOGIN_USER WHERE DIVISION_ID = @ID;
	END
	ELSE IF @ENTITY = 'SECTION'
	BEGIN
		SELECT @CODE = SECTION_CODE, @PARENT = DEPARTMENT_CODE FROM dbo.TB_M_SECTION WHERE SECTION_ID = @ID;
		IF EXISTS (SELECT 1 FROM dbo.TB_M_SECTION WHERE SECTION_CODE = @CODE AND DEPARTMENT_CODE = @PARENT AND ISNULL(DELETE_FLAG, 0) = 0 AND SECTION_ID <> @ID)
			SET @RETURN_MSG = 'ERROR: An active Section already uses code ' + @CODE + ' in Department ' + @PARENT + '.';
		ELSE IF EXISTS (SELECT 1 FROM dbo.TB_M_DEPARTMENT WHERE DEPARTMENT_CODE = @PARENT) AND NOT EXISTS (SELECT 1 FROM dbo.TB_M_DEPARTMENT WHERE DEPARTMENT_CODE = @PARENT AND ISNULL(DELETE_FLAG, 0) = 0)
			SET @RETURN_MSG = 'ERROR: Activate Department ' + ISNULL(@PARENT, '-') + ' before Section ' + @CODE + '.';
		ELSE
			UPDATE dbo.TB_M_SECTION SET DELETE_FLAG = 0, CHANGED_DT = GETDATE(), CHANGED_BY = @LOGIN_USER WHERE SECTION_ID = @ID;
	END
	ELSE IF @ENTITY = 'POSITION'
	BEGIN
		SELECT @CODE = POSITION_NAME FROM dbo.TB_M_POSITION WHERE POSITION_ID = @ID;
		IF EXISTS (SELECT 1 FROM dbo.TB_M_POSITION WHERE POSITION_NAME = @CODE AND ISNULL(DELETE_FLAG, 0) = 0 AND POSITION_ID <> @ID)
			SET @RETURN_MSG = 'ERROR: An active Position already uses the name ' + @CODE + '.';
		ELSE
			UPDATE dbo.TB_M_POSITION SET DELETE_FLAG = 0, CHANGED_DT = GETDATE(), CHANGED_BY = @LOGIN_USER WHERE POSITION_ID = @ID;
	END
	ELSE IF @ENTITY = 'DOCUMENT'
	BEGIN
		-- DELETE_FLAG = 2 = Deleted (sp_DocumentMaster_Remove): tidak bisa diaktifkan lagi.
		SELECT @CODE = DOCUMENT_CODE FROM dbo.TB_M_DOCUMENT WHERE DOCUMENT_ID = @ID AND ISNULL(DELETE_FLAG, 0) <> 2;
		IF @CODE IS NULL
			SET @RETURN_MSG = 'ERROR: Data not found. It may have been removed - refresh the page.';
		ELSE IF EXISTS (SELECT 1 FROM dbo.TB_M_DOCUMENT WHERE DOCUMENT_CODE = @CODE AND ISNULL(DELETE_FLAG, 0) = 0 AND DOCUMENT_ID <> @ID)
			SET @RETURN_MSG = 'ERROR: An active Document Category already uses code ' + @CODE + '.';
		ELSE
			UPDATE dbo.TB_M_DOCUMENT SET DELETE_FLAG = 0, CHANGED_DT = GETDATE(), CHANGED_BY = @LOGIN_USER WHERE DOCUMENT_ID = @ID;
	END
	ELSE
		SET @RETURN_MSG = 'ERROR: Unknown master data type.';

	IF @RETURN_MSG IS NULL AND @CODE IS NULL
		SET @RETURN_MSG = 'ERROR: Data not found. It may have been removed - refresh the page.';

	IF @RETURN_MSG IS NOT NULL
	BEGIN
		EXEC sp_WriteLog @PROCESS_ID, '3', 'ERR', @RETURN_MSG, @LOCATION, @LOGIN_USER;
		RETURN 0;
	END

	SET @RETURN_MSG = 'Successfully activated';
	EXEC sp_WriteLog @PROCESS_ID, '2', 'INF', @RETURN_MSG, @LOCATION, @LOGIN_USER;
	RETURN 1;
END TRY
BEGIN CATCH
	SET @RETURN_MSG = 'ERROR: ' + ERROR_PROCEDURE() + ': ' + ERROR_MESSAGE() + ', at line = ' + CAST(ERROR_LINE() AS VARCHAR);
	EXEC sp_WriteLog @PROCESS_ID, '4', 'ERR', @RETURN_MSG, @LOCATION, @LOGIN_USER;
	RETURN 0;
END CATCH
GO
