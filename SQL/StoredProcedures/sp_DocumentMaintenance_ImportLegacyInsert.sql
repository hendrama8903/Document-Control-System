CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentMaintenance_ImportLegacyInsert]
	@DOCUMENT_CODE				VARCHAR(25),
	@DOCUMENT_TRANSACTION_NAME	VARCHAR(255),
	@DOCUMENT_ID				INT,
	@LEVEL_CODE					INT,
	@DIVISION					VARCHAR(255),
	@DEPARTMENT					INT,
	@CLASSIFIED					INT,
	@REVISION					INT,
	@DOCUMENT_DATE				DATETIME,
	@FILE_PATH					VARCHAR(255),
	@DOCUMENT_CREATOR			VARCHAR(255),
	@REASON						VARCHAR(255),
	@CREATED_BY					VARCHAR(50),
	@RETURN_MSG					VARCHAR(MAX) OUTPUT,
	@RETURN_ID					VARCHAR(MAX) OUTPUT,
	-- Recipients already holding this revision, from the master list (2026-11-12):
	-- "DEPARTMENT_ID|yyyy-MM-dd;..." . Empty = no P4D registration, as before.
	@DISTRIBUTION				VARCHAR(MAX) = NULL,
	-- Management System (QMS / K3L / SMK3 / EMS, 2026-11-19). NULL = QMS. Archived systems are
	-- allowed here: an import brings old documents.
	@MGMT_SYSTEM				VARCHAR(10) = NULL
AS
BEGIN TRY
	DECLARE @PROCESS_ID BIGINT
	, @LOCATION VARCHAR(255) = 'sp_DocumentMaintenance_ImportLegacyInsert'
	, @REVIEW_CYCLE_MONTHS INT
	, @NEXT_REVIEW_DATE DATETIME
	, @outerTran INT = NULL

	EXEC sp_StartLog @PROCESS_ID OUTPUT, 'Document Maintenance', 'Import Legacy Insert', @LOCATION, @CREATED_BY

	IF EXISTS (
		SELECT 1 FROM TB_R_DOCUMENT
		WHERE DOCUMENT_CODE = @DOCUMENT_CODE AND ISNULL(DELETE_FLAG, 0) = 0
	)
	BEGIN
		SET @RETURN_ID = 0;
		SET @RETURN_MSG = 'ERROR: Document Code ' + @DOCUMENT_CODE + ' is already registered';
		EXEC sp_WriteLog @PROCESS_ID, '3', 'ERR', @RETURN_MSG, @LOCATION, @CREATED_BY
		RETURN 0;
	END

	SELECT @REVIEW_CYCLE_MONTHS = REVIEW_CYCLE_MONTHS FROM TB_M_DOCUMENT WHERE DOCUMENT_ID = @DOCUMENT_ID

	IF @REVIEW_CYCLE_MONTHS IS NOT NULL
	BEGIN
		SET @NEXT_REVIEW_DATE = DATEADD(MONTH, @REVIEW_CYCLE_MONTHS, GETDATE())
	END

	-- Snapshot nama Division/Department (request Hendra 2026-08-22), lihat
	-- SQL/OrgMasterData_NameSnapshot_Migration.sql.
	DECLARE @snap_DIVISION_NAME VARCHAR(255), @snap_DEPARTMENT_CODE VARCHAR(5), @snap_DEPARTMENT_NAME VARCHAR(255);

	SELECT @snap_DIVISION_NAME = DIVISION_NAME FROM TB_M_DIVISION WHERE DIVISION_CODE = @DIVISION;
	SELECT @snap_DEPARTMENT_CODE = DEPARTMENT_CODE, @snap_DEPARTMENT_NAME = DEPARTMENT_NAME FROM TB_M_DEPARTMENT WHERE DEPARTMENT_ID = @DEPARTMENT;

	-- Prefix and sequence number from the code (2026-11-12): "ITD/SOP-APP-00/001"
	-- -> prefix "ITD/SOP-APP-00", number 1. Section (level 3/4) is the part of the
	-- prefix after the last '-', e.g. "00". The template has no Section column, so
	-- without this the migrated documents had no Section.
	DECLARE @lastSlash INT = CHARINDEX('/', REVERSE(@DOCUMENT_CODE)),
			@seqPrefix VARCHAR(25), @seqPart VARCHAR(25), @seqNo INT,
			@SECTION_CODE VARCHAR(50), @snap_SECTION_NAME VARCHAR(255);

	IF @lastSlash > 1
	BEGIN
		SET @seqPrefix = LEFT(@DOCUMENT_CODE, LEN(@DOCUMENT_CODE) - @lastSlash);
		SET @seqPart   = RIGHT(@DOCUMENT_CODE, @lastSlash - 1);
		IF @seqPart NOT LIKE '%[^0-9]%' AND LEN(@seqPart) BETWEEN 1 AND 3
			SET @seqNo = CAST(@seqPart AS INT);
	END

	IF @LEVEL_CODE IN (3, 4) AND @seqPrefix IS NOT NULL AND CHARINDEX('-', @seqPrefix) > 0
	BEGIN
		SET @SECTION_CODE = RIGHT(@seqPrefix, CHARINDEX('-', REVERSE(@seqPrefix)) - 1);
		SELECT @snap_SECTION_NAME = SECTION_NAME FROM TB_M_SECTION
		WHERE SECTION_CODE = @SECTION_CODE AND DEPARTMENT_CODE = @snap_DEPARTMENT_CODE;
	END

	-- Level 1/2 "HMMI/PRO/PD/001": company and (level 2) process from the code, kept only
	-- when they are in the master, like the normal flow stores them.
	DECLARE @COMPANY_CODE VARCHAR(50), @PROCESS_CODE VARCHAR(50);
	IF @LEVEL_CODE IN (1, 2) AND CHARINDEX('/', @DOCUMENT_CODE) > 1
	BEGIN
		SELECT @COMPANY_CODE = SYSTEM_CODE FROM TB_M_SYSTEM
		WHERE SYSTEM_TYPE = 'COMPANY_CODE' AND SYSTEM_CODE = LEFT(@DOCUMENT_CODE, CHARINDEX('/', @DOCUMENT_CODE) - 1);
		IF @LEVEL_CODE = 2 AND CHARINDEX('/', @seqPrefix) > 0
			SELECT @PROCESS_CODE = SYSTEM_CODE FROM TB_M_SYSTEM
			WHERE SYSTEM_TYPE = 'PROCESS_CODE' AND SYSTEM_CODE = RIGHT(@seqPrefix, CHARINDEX('/', REVERSE(@seqPrefix)) - 1);
	END

	-- Own transaction, or a savepoint when the caller already has one.
	SET @outerTran = @@TRANCOUNT;
	IF @outerTran = 0 BEGIN TRANSACTION; ELSE SAVE TRANSACTION ImportLegacyInsert;

	INSERT INTO [dbo].[TB_R_DOCUMENT]
		(DOCUMENT_CODE, DOCUMENT_TRANSACTION_NAME, DOCUMENT_ID, LEVEL_CODE, DIVISION, DIVISION_NAME, DEPARTMENT, DEPARTMENT_CODE, DEPARTMENT_NAME,
		 SECTION_CODE, SECTION_NAME, COMPANY_CODE, PROCESS_CODE, DOCUMENT_TYPE, EXTERNAL_FLAG,
		 CLASSIFIED, REVISION, DOCUMENT_DATE, FILE_PATH, DOCUMENT_CREATOR, REASON, SOURCE,
		 STATUS, APPROVAL_ID, DELETE_FLAG, NEXT_REVIEW_DATE,
		 CREATED_BY, CREATED_DT, CHANGED_BY, CHANGED_DT, MGMT_SYSTEM)
	VALUES
		(@DOCUMENT_CODE, @DOCUMENT_TRANSACTION_NAME, @DOCUMENT_ID, @LEVEL_CODE, @DIVISION, @snap_DIVISION_NAME, @DEPARTMENT, @snap_DEPARTMENT_CODE, @snap_DEPARTMENT_NAME,
		 @SECTION_CODE, @snap_SECTION_NAME, @COMPANY_CODE, @PROCESS_CODE,
		 -- DOCUMENT_TYPE New/Revision and EXTERNAL_FLAG like the normal flow (2026-11-12): the
		 -- User Dashboard and P4D Maintenance searches inner-join DOCUMENT_TYPE.
		 IIF(@REVISION > 0, '02', '01'), '0',
		 @CLASSIFIED, @REVISION, @DOCUMENT_DATE, @FILE_PATH, @DOCUMENT_CREATOR, @REASON, 'MIGRATION',
		 '1', NULL, 0, @NEXT_REVIEW_DATE,
		 @CREATED_BY, GETDATE(), @CREATED_BY, GETDATE(), ISNULL(NULLIF(@MGMT_SYSTEM, ''), 'QMS'))

	SET @RETURN_ID = SCOPE_IDENTITY();

	-- Raise the DOC_NO counter for this prefix (2026-11-12), same rule as the manual
	-- number path in sp_generate_doc_no: only ever upward. Otherwise the next
	-- generated number (e.g. .../001) clashes with a migrated document.
	IF @seqNo IS NOT NULL
	BEGIN
		IF NOT EXISTS (SELECT 1 FROM TB_M_SEQUENCE WHERE SEQ_TYPE = 'DOC_NO' AND SEQ_CODE = @seqPrefix)
			INSERT INTO TB_M_SEQUENCE (SEQ_TYPE, SEQ_CODE, SEQ_NO, CREATED_BY, CREATED_DT, CHANGED_BY, CHANGED_DT)
			VALUES ('DOC_NO', @seqPrefix, @seqNo, @CREATED_BY, GETDATE(), @CREATED_BY, GETDATE());
		ELSE
			UPDATE TB_M_SEQUENCE
			SET SEQ_NO = @seqNo, CHANGED_BY = @CREATED_BY, CHANGED_DT = GETDATE()
			WHERE SEQ_TYPE = 'DOC_NO' AND SEQ_CODE = @seqPrefix AND SEQ_NO < @seqNo;
	END

	-- Distribution already done on paper (2026-11-12, agreed with QMS): register the
	-- document in P4D in its final state - registration Sent (5), every recipient
	-- sent (1) on the date of the master list, and acknowledged on that same date
	-- (TB_R_PUBLISH_HISTORY), so the document is Published (5). Same rows the normal
	-- flow leaves behind (sp_P4DMaintenance_Insert / SendDistributionAll /
	-- sp_UserDashboard_Acknowledge). The P4D registration also lets the document be
	-- revised later (sp_DocumentMaintenance_Insert requires it).
	IF NULLIF(LTRIM(RTRIM(@DISTRIBUTION)), '') IS NOT NULL
	BEGIN
		DECLARE @dist TABLE (DEPARTMENT_ID INT PRIMARY KEY, DIST_DATE DATE);
		DECLARE @CTRL_ID INT;

		INSERT INTO @dist (DEPARTMENT_ID, DIST_DATE)
		SELECT CAST(LEFT(v, CHARINDEX('|', v) - 1) AS INT), MIN(CAST(SUBSTRING(v, CHARINDEX('|', v) + 1, 10) AS DATE))
		FROM (SELECT LTRIM(RTRIM(value)) AS v FROM STRING_SPLIT(@DISTRIBUTION, ';')) s
		WHERE CHARINDEX('|', v) > 1
		GROUP BY CAST(LEFT(v, CHARINDEX('|', v) - 1) AS INT);

		IF EXISTS (SELECT 1 FROM @dist d WHERE NOT EXISTS (SELECT 1 FROM TB_M_DEPARTMENT m WHERE m.DEPARTMENT_ID = d.DEPARTMENT_ID))
			THROW 50001, 'A distribution department is not in Department master.', 1;

		INSERT INTO TB_R_CTRL_DOCUMENT
			(DOCUMENT_CODE, DOCUMENT_NAME, DOCUMENT_TYPE, PROCESS_CODE, COMPANY_CODE, SECTION_CODE, ITEM_CHANGED, REASON,
			 EXTERNAL_FLAG, REFERENCE_NO, SOURCE, DOCUMENT_DATE, FILE_PATH, STATUS, REVISION, APPROVAL_ID, DELETE_FLAG,
			 DEPARTMENT_ID, DEPARTMENT_CODE, DEPARTMENT_NAME, DIVISION, DIVISION_NAME, OPERATION_TYPE, DOCUMENT_TRANSACTION_ID,
			 REMARKS, CREATED_BY, CREATED_DT, CHANGED_BY, CHANGED_DT)
		SELECT DOCUMENT_CODE, DOCUMENT_TRANSACTION_NAME, DOCUMENT_TYPE, PROCESS_CODE, COMPANY_CODE, SECTION_CODE, ITEM_CHANGED, REASON,
			 EXTERNAL_FLAG, REFERENCE_NO, SOURCE, DOCUMENT_DATE, FILE_PATH, '5', REVISION, APPROVAL_ID, 0,
			 DEPARTMENT, DEPARTMENT_CODE, DEPARTMENT_NAME, DIVISION, DIVISION_NAME, 1, DOCUMENT_TRANSACTION_ID,
			 'Distribution imported from the master list', @CREATED_BY, GETDATE(), @CREATED_BY, GETDATE()
		FROM TB_R_DOCUMENT WHERE DOCUMENT_TRANSACTION_ID = @RETURN_ID;
		SET @CTRL_ID = SCOPE_IDENTITY();

		INSERT INTO TB_R_DOCUMENT_DISTRIBUTION
			(DOCUMENT_TRANSACTION_ID, DEPARTMENT_ID, DISTRIBUTION_DATE, STATUS, DIVISION, DIVISION_NAME, DEPARTMENT_CODE, DEPARTMENT_NAME,
			 CREATED_BY, CREATED_DT, CHANGED_BY, CHANGED_DT)
		SELECT @RETURN_ID, d.DEPARTMENT_ID, d.DIST_DATE, '1', m.DIVISION, v.DIVISION_NAME, m.DEPARTMENT_CODE, m.DEPARTMENT_NAME,
			 @CREATED_BY, GETDATE(), @CREATED_BY, GETDATE()
		FROM @dist d
		JOIN TB_M_DEPARTMENT m ON m.DEPARTMENT_ID = d.DEPARTMENT_ID
		LEFT JOIN TB_M_DIVISION v ON v.DIVISION_CODE = m.DIVISION;

		-- Acknowledged when the paper copy was handed over.
		INSERT INTO TB_R_PUBLISH_HISTORY
			(DOCUMENT_CTRL_ID, DEPARTMENT_ID, DEPARTMENT_CODE, DEPARTMENT_NAME, CREATED_BY, CREATED_DT, CHANGED_BY, CHANGED_DT)
		SELECT @CTRL_ID, d.DEPARTMENT_ID, m.DEPARTMENT_CODE, m.DEPARTMENT_NAME,
			 @CREATED_BY, CAST(d.DIST_DATE AS DATETIME), @CREATED_BY, GETDATE()
		FROM @dist d
		JOIN TB_M_DEPARTMENT m ON m.DEPARTMENT_ID = d.DEPARTMENT_ID;

		UPDATE TB_R_DOCUMENT SET STATUS = '5' WHERE DOCUMENT_TRANSACTION_ID = @RETURN_ID;
	END

	IF @outerTran = 0 COMMIT TRANSACTION;

	SET @RETURN_MSG = 'Successfully Save Data'
	EXEC sp_WriteLog @PROCESS_ID, '2', 'INF', @RETURN_MSG, @LOCATION, @CREATED_BY
	RETURN 1;
END TRY
BEGIN CATCH
	IF @outerTran = 0 AND @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
	ELSE IF @outerTran > 0 AND XACT_STATE() = 1 ROLLBACK TRANSACTION ImportLegacyInsert;
	SET @RETURN_ID = 0;
	SET @RETURN_MSG = 'ERROR: ' + ERROR_PROCEDURE() +': '+ ERROR_MESSAGE() + ', at line = ' +  CAST(ERROR_LINE() AS VARCHAR);
	EXEC sp_WriteLog @PROCESS_ID, '4', 'ERR', @RETURN_MSG, @LOCATION, @CREATED_BY
	RETURN 0;
END CATCH
GO
