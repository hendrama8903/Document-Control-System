-- Access Rights Review: katalog menu + fungsi aktif, urut seperti sidebar,
-- dengan daftar role yang diberi akses (GRANTED_ROLES, dipisah koma).
-- ITEM_TYPE: MENU (halaman) / FUNCTION (tombol/aksi di halaman itu).
-- Result set kedua: daftar role + jumlah user aktif.
CREATE OR ALTER PROCEDURE [dbo].[sp_AccessRight_Matrix]
AS
BEGIN
	SET NOCOUNT ON;

	;WITH ITEMS AS (
		SELECT
			'MENU' AS ITEM_TYPE,
			M.MENU_ID AS ITEM_ID,
			M.MENU_ID,
			ISNULL(P.MENU_NAME, '') AS PARENT_NAME,
			M.MENU_NAME,
			M.MENU_URL,
			CAST(NULL AS VARCHAR(255)) AS FUNCTION_ID,
			CAST(NULL AS VARCHAR(255)) AS FUNCTION_NAME,
			ISNULL(P.MENU_SEQ, M.MENU_SEQ) AS S1,
			ISNULL(P.MENU_ID, M.MENU_ID) AS S2,
			CASE WHEN P.MENU_ID IS NULL THEN 0 ELSE M.MENU_SEQ END AS S3,
			0 AS S4
		FROM dbo.TB_M_MENU M
		LEFT JOIN dbo.TB_M_MENU P ON P.MENU_ID = M.PARENT_ID
		WHERE ISNULL(M.DELETE_FLAG, 0) = 0 AND ISNULL(P.DELETE_FLAG, 0) = 0
		  AND ISNULL(M.MENU_URL, '#') <> '#'
		UNION ALL
		SELECT
			'FUNCTION', F.FUNCTION_ID, M.MENU_ID,
			ISNULL(P.MENU_NAME, ''), M.MENU_NAME, M.MENU_URL,
			F.FUNCTION_ID, F.FUNCTION_NAME,
			ISNULL(P.MENU_SEQ, M.MENU_SEQ), ISNULL(P.MENU_ID, M.MENU_ID),
			CASE WHEN P.MENU_ID IS NULL THEN 0 ELSE M.MENU_SEQ END, 1
		FROM dbo.TB_M_FUNCTION F
		JOIN dbo.TB_M_MENU M ON M.MENU_ID = F.MENU_ID
		LEFT JOIN dbo.TB_M_MENU P ON P.MENU_ID = M.PARENT_ID
		WHERE ISNULL(F.DELETE_FLAG, 0) = 0 AND ISNULL(M.DELETE_FLAG, 0) = 0 AND ISNULL(P.DELETE_FLAG, 0) = 0
	)
	SELECT
		I.ITEM_TYPE, I.ITEM_ID, I.MENU_ID, I.PARENT_NAME, I.MENU_NAME, I.MENU_URL,
		I.FUNCTION_ID, I.FUNCTION_NAME,
		CASE WHEN I.ITEM_TYPE = 'MENU'
			THEN (SELECT STRING_AGG(A.ROLE_ID, ',') FROM dbo.TB_M_AUTH_MENU A WHERE A.MENU_ID = I.ITEM_ID)
			ELSE (SELECT STRING_AGG(A.ROLE_ID, ',') FROM dbo.TB_M_AUTH_FUNCTION A WHERE A.FUNCTION_ID = I.ITEM_ID)
		END AS GRANTED_ROLES
	FROM ITEMS I
	ORDER BY I.S1, I.S2, I.S3, I.MENU_ID, I.S4, I.FUNCTION_ID;

	SELECT R.ROLE_ID, R.ROLE_NAME, R.ROLE_DESC,
		(SELECT COUNT(*) FROM dbo.TB_M_USER U WHERE U.ROLE_ID = R.ROLE_ID AND ISNULL(U.DELETE_FLAG, '0') <> '1') AS ACTIVE_USERS
	FROM dbo.TB_M_ROLE R
	ORDER BY R.ROLE_NAME;
END
GO
