-- Catat satu akses dokumen (lihat SQL/DocumentAccessLog_Migration.sql).
-- Dokumen dikenali dari @DOCUMENT_TRANSACTION_ID, @EXTERNAL_DOCUMENT_ID, atau
-- @FILE_PATH (dicari di dokumen aktif, lalu riwayat revisi, lalu dokumen
-- eksternal). Data dokumen disimpan sebagai snapshot supaya log tetap terbaca
-- walau dokumennya kemudian direvisi/dihapus.
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentAccessLog_Insert]
	@USERNAME                 VARCHAR(50),
	@ACTION                   VARCHAR(10),
	@DOCUMENT_TRANSACTION_ID  INT = NULL,
	@EXTERNAL_DOCUMENT_ID     INT = NULL,
	@FILE_PATH                VARCHAR(500) = NULL,
	@COPIES                   INT = NULL,
	@SOURCE_PAGE              VARCHAR(255) = NULL,
	@CLIENT_IP                VARCHAR(64) = NULL,
	@USER_AGENT               VARCHAR(500) = NULL
AS
BEGIN
	SET NOCOUNT ON;
	SET @FILE_PATH = NULLIF(LTRIM(RTRIM(@FILE_PATH)), '');

	DECLARE @SOURCE_TYPE VARCHAR(10) = 'INTERNAL', @CODE VARCHAR(255), @TITLE VARCHAR(500),
			@REV VARCHAR(50), @DEPT VARCHAR(255), @PATH VARCHAR(500) = @FILE_PATH;

	IF @DOCUMENT_TRANSACTION_ID IS NULL AND @EXTERNAL_DOCUMENT_ID IS NULL AND @FILE_PATH IS NOT NULL
	BEGIN
		SELECT TOP 1 @DOCUMENT_TRANSACTION_ID = DOCUMENT_TRANSACTION_ID
		FROM dbo.TB_R_DOCUMENT WHERE LTRIM(RTRIM(FILE_PATH)) = @FILE_PATH
		ORDER BY DOCUMENT_TRANSACTION_ID DESC;

		IF @DOCUMENT_TRANSACTION_ID IS NULL
			SELECT TOP 1 @CODE = DOCUMENT_CODE, @REV = CAST(REVISION AS VARCHAR(50))
			FROM dbo.TB_R_DOCUMENT_HISTORY WHERE LTRIM(RTRIM(FILE_PATH)) = @FILE_PATH;

		IF @DOCUMENT_TRANSACTION_ID IS NULL AND @CODE IS NULL
			SELECT TOP 1 @EXTERNAL_DOCUMENT_ID = EXTERNAL_DOCUMENT_ID
			FROM dbo.TB_M_EXTERNAL_DOCUMENT WHERE LTRIM(RTRIM(FILE_PATH)) = @FILE_PATH;
	END

	IF @DOCUMENT_TRANSACTION_ID IS NOT NULL
		SELECT @CODE = DOCUMENT_CODE, @TITLE = DOCUMENT_TRANSACTION_NAME, @REV = CAST(REVISION AS VARCHAR(50)),
			   @DEPT = DEPARTMENT_NAME, @PATH = ISNULL(@PATH, FILE_PATH)
		FROM dbo.TB_R_DOCUMENT WHERE DOCUMENT_TRANSACTION_ID = @DOCUMENT_TRANSACTION_ID;
	ELSE IF @EXTERNAL_DOCUMENT_ID IS NOT NULL
		SELECT @SOURCE_TYPE = 'EXTERNAL', @TITLE = DOCUMENT_NAME, @REV = REVISION_EDITION,
			   @DEPT = DEPARTMENT_NAME, @PATH = ISNULL(@PATH, FILE_PATH)
		FROM dbo.TB_M_EXTERNAL_DOCUMENT WHERE EXTERNAL_DOCUMENT_ID = @EXTERNAL_DOCUMENT_ID;

	INSERT INTO dbo.TB_R_DOCUMENT_ACCESS_LOG
		(USERNAME, USER_FULL_NAME, ACTION, SOURCE_TYPE, DOCUMENT_TRANSACTION_ID, EXTERNAL_DOCUMENT_ID,
		 DOCUMENT_CODE, DOCUMENT_TITLE, REVISION, DEPARTMENT_NAME, FILE_PATH, COPIES, SOURCE_PAGE, CLIENT_IP, USER_AGENT)
	SELECT @USERNAME, U.FULL_NAME, @ACTION, @SOURCE_TYPE, @DOCUMENT_TRANSACTION_ID, @EXTERNAL_DOCUMENT_ID,
		 @CODE, @TITLE, @REV, @DEPT, LEFT(@PATH, 500), @COPIES, LEFT(@SOURCE_PAGE, 255), @CLIENT_IP, LEFT(@USER_AGENT, 500)
	FROM (SELECT 1 AS X) X
	LEFT JOIN dbo.TB_M_USER U ON U.USERNAME = @USERNAME;
END
GO
