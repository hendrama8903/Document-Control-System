-- Laporan Document Access Log (menu Administration > Document Access Log).
-- Filter opsional; @KEYWORD dicocokkan ke nomor & judul dokumen. TOTAL_ROWS =
-- jumlah baris sebelum paging. Tanpa @PageNumber/@PageSize = semua baris (export).
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentAccessLog_Search]
	@START_DT    DATETIME = NULL,
	@END_DT      DATETIME = NULL,
	@ACTION      VARCHAR(10) = NULL,
	@USERNAME    VARCHAR(50) = NULL,
	@KEYWORD     VARCHAR(255) = NULL,
	@PageNumber  INT = NULL,
	@PageSize    INT = NULL
AS
BEGIN
	SET NOCOUNT ON;
	SET @ACTION = NULLIF(@ACTION, '');
	SET @USERNAME = NULLIF(@USERNAME, '');
	SET @KEYWORD = NULLIF(LTRIM(RTRIM(@KEYWORD)), '');

	;WITH data AS (
		SELECT
			L.ACCESS_LOG_ID, L.ACCESS_DT, L.USERNAME, L.USER_FULL_NAME, L.ACTION, L.SOURCE_TYPE,
			L.DOCUMENT_TRANSACTION_ID, L.EXTERNAL_DOCUMENT_ID, L.DOCUMENT_CODE, L.DOCUMENT_TITLE, L.REVISION,
			L.DEPARTMENT_NAME, L.FILE_PATH, L.COPIES, L.SOURCE_PAGE, L.CLIENT_IP, L.USER_AGENT,
			ROW_NUMBER() OVER (ORDER BY L.ACCESS_DT DESC, L.ACCESS_LOG_ID DESC) AS ROW_NUM,
			COUNT(*) OVER () AS TOTAL_ROWS
		FROM dbo.TB_R_DOCUMENT_ACCESS_LOG L
		WHERE (@START_DT IS NULL OR L.ACCESS_DT >= @START_DT)
		AND (@END_DT IS NULL OR L.ACCESS_DT < DATEADD(DAY, 1, CAST(@END_DT AS DATE)))
		AND (@ACTION IS NULL OR L.ACTION = @ACTION)
		AND (@USERNAME IS NULL OR L.USERNAME = @USERNAME)
		AND (@KEYWORD IS NULL OR L.DOCUMENT_CODE LIKE '%' + @KEYWORD + '%' OR L.DOCUMENT_TITLE LIKE '%' + @KEYWORD + '%')
	)
	SELECT * FROM data
	WHERE @PageNumber IS NULL OR @PageSize IS NULL
	   OR (ROW_NUM > @PageSize * (@PageNumber - 1) AND ROW_NUM <= @PageSize * @PageNumber)
	ORDER BY ROW_NUM;
END
GO
