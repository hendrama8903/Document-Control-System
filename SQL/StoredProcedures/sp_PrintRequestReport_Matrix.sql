-- Print Request Report (2026-11-19): the approved Print Request lines in the Master List
-- layout - one row per document + revision, one column per requesting division, a cell
-- line per request "QTY:DEPT-ddMMMyy" (request date). Grouped like the Master List by the
-- department that owns the document. Read by PrintRequestMatrixService.
--   1. lines      every approved, not deleted request line in the date range
--   2. divisions  the active divisions = the columns
CREATE OR ALTER PROCEDURE [dbo].[sp_PrintRequestReport_Matrix]
    @DATE_FROM        DATE = NULL,          -- request date, inclusive
    @DATE_TO          DATE = NULL,          -- request date, inclusive
    @DIVISION         VARCHAR(50) = NULL,   -- owning division of the document (NULL = all)
    @DEPARTMENT_CODE  VARCHAR(50) = NULL    -- owning department of the document (NULL = all)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        D.REQUEST_DETAIL_ID,
        H.REQUEST_NO,
        H.REQUEST_DATE,
        D.DOCUMENT_CODE,
        D.DOCUMENT_NAME,
        ISNULL(D.REVISION_NO, 0) AS REVISION,
        D.COPY_TYPE,
        ISNULL(D.COPY_QTY, 0) AS COPY_QTY,
        ISNULL(D.PRINT_STATUS, '0') AS PRINT_STATUS,
        D.PRINTED_DT,
        -- who asked
        H.DIVISION AS REQ_DIVISION,
        ISNULL(H.DEPARTMENT_CODE, RDEP.DEPARTMENT_CODE) AS REQ_DEPARTMENT_CODE,
        -- who owns the document (current row, else the superseded revision in history)
        COALESCE(DOC.DIVISION, HIS.DIVISION) AS OWN_DIVISION,
        COALESCE(DOC.DIVISION_NAME, HIS.DIVISION_NAME, ODIV.DIVISION_NAME) AS OWN_DIVISION_NAME,
        COALESCE(DOC.DEPARTMENT_CODE, HIS.DEPARTMENT_CODE, ODEP.DEPARTMENT_CODE) AS OWN_DEPARTMENT_CODE,
        COALESCE(DOC.DEPARTMENT_NAME, HIS.DEPARTMENT_NAME, ODEP.DEPARTMENT_NAME) AS OWN_DEPARTMENT_NAME,
        DCAT.DOCUMENT_CODE AS CATEGORY_CODE
    INTO #LINE
    FROM [dbo].[TB_R_COPY_REQUEST_D] D
    JOIN [dbo].[TB_R_COPY_REQUEST_H] H ON H.REQUEST_ID = D.REQUEST_ID
    LEFT JOIN [dbo].[TB_M_DEPARTMENT] RDEP ON RDEP.DEPARTMENT_ID = H.DEPARTMENT_ID
    LEFT JOIN [dbo].[TB_R_DOCUMENT] DOC ON DOC.DOCUMENT_TRANSACTION_ID = D.DOCUMENT_TRANSACTION_ID
    OUTER APPLY (
        SELECT TOP 1 X.DIVISION, X.DIVISION_NAME, X.DEPARTMENT, X.DEPARTMENT_CODE, X.DEPARTMENT_NAME, X.DOCUMENT_ID
        FROM [dbo].[TB_R_DOCUMENT_HISTORY] X
        WHERE DOC.DOCUMENT_TRANSACTION_ID IS NULL AND X.DOCUMENT_TRANSACTION_ID = D.DOCUMENT_TRANSACTION_ID
        ORDER BY X.DOCUMENT_HISTORY_ID DESC
    ) HIS
    LEFT JOIN [dbo].[TB_M_DEPARTMENT] ODEP ON ODEP.DEPARTMENT_ID = COALESCE(DOC.DEPARTMENT, HIS.DEPARTMENT)
    LEFT JOIN [dbo].[TB_M_DIVISION] ODIV ON ODIV.DIVISION_CODE = COALESCE(DOC.DIVISION, HIS.DIVISION)
    LEFT JOIN [dbo].[TB_M_DOCUMENT] DCAT ON DCAT.DOCUMENT_ID = COALESCE(DOC.DOCUMENT_ID, HIS.DOCUMENT_ID)
    WHERE ISNULL(D.DELETE_FLAG, 0) = 0
      AND ISNULL(H.DELETE_FLAG, 0) = 0
      AND H.STATUS = '2'                     -- approved requests only
      AND (@DATE_FROM IS NULL OR CAST(H.REQUEST_DATE AS DATE) >= @DATE_FROM)
      AND (@DATE_TO IS NULL OR CAST(H.REQUEST_DATE AS DATE) <= @DATE_TO);

    SELECT * FROM #LINE
    WHERE (@DIVISION IS NULL OR OWN_DIVISION = @DIVISION)
      AND (@DEPARTMENT_CODE IS NULL OR OWN_DEPARTMENT_CODE = @DEPARTMENT_CODE)
    ORDER BY OWN_DIVISION, OWN_DEPARTMENT_CODE, DOCUMENT_CODE, REVISION, REQUEST_DATE, REQ_DEPARTMENT_CODE;

    SELECT DIVISION_CODE, DIVISION_NAME
    FROM [dbo].[TB_M_DIVISION]
    WHERE ISNULL(DELETE_FLAG, '0') = '0';

    DROP TABLE #LINE;
END
GO
