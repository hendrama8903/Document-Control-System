-- Bahan peringatan dampak sebelum alur diubah, dinonaktifkan, diaktifkan, atau
-- dihapus (Approval Workflow Setup). Request Hendra 2026-11-07.
--
-- IN_PROGRESS_DOCS / REJECTED_DOCS adalah dokumen yang saat ini memakai alur ini:
-- level dan kategorinya cocok, dan level jabatan pembuatnya sama. TB_R_APPROVAL_H
-- belum mencatat WORKFLOW_DOC_ID, jadi angkanya perkiraan dari data sekarang.
CREATE OR ALTER PROCEDURE [dbo].[sp_Workflow_DocImpact]
	@WORKFLOW_DOC_ID INT
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @DOCUMENT_LEVEL INT, @CREATOR_LEVEL INT, @DOCUMENT_ID INT, @IS_ACTIVE BIT;

	SELECT @DOCUMENT_LEVEL = DOCUMENT_LEVEL, @CREATOR_LEVEL = CREATOR_LEVEL, @DOCUMENT_ID = DOCUMENT_ID, @IS_ACTIVE = IS_ACTIVE
	FROM dbo.TB_M_WORKFLOW_DOC_H
	WHERE WORKFLOW_DOC_ID = @WORKFLOW_DOC_ID;

	IF @DOCUMENT_LEVEL IS NULL RETURN;

	;WITH DOCS AS (
		SELECT D.STATUS
		FROM dbo.TB_R_DOCUMENT D
		CROSS APPLY dbo.fn_WorkflowDoc_Creator(D.DOCUMENT_CREATOR) C
		WHERE ISNULL(D.DELETE_FLAG, 0) = 0
		AND D.APPROVAL_ID IS NOT NULL
		AND TRY_CONVERT(INT, D.LEVEL_CODE) = @DOCUMENT_LEVEL
		AND C.POSITION_LEVEL = @CREATOR_LEVEL
		AND (
			(@DOCUMENT_ID IS NOT NULL AND TRY_CONVERT(INT, D.DOCUMENT_ID) = @DOCUMENT_ID)
			OR (@DOCUMENT_ID IS NULL AND NOT EXISTS (
				SELECT 1 FROM dbo.TB_M_WORKFLOW_DOC_H O
				WHERE O.IS_ACTIVE = 1 AND O.CREATOR_LEVEL = @CREATOR_LEVEL
				AND O.DOCUMENT_ID = TRY_CONVERT(INT, D.DOCUMENT_ID)))
		)
	)
	SELECT
		@IS_ACTIVE AS IS_ACTIVE,
		@DOCUMENT_LEVEL AS DOCUMENT_LEVEL,
		@CREATOR_LEVEL AS CREATOR_LEVEL,
		@DOCUMENT_ID AS DOCUMENT_ID,
		(SELECT DOCUMENT_CODE FROM dbo.TB_M_DOCUMENT WHERE DOCUMENT_ID = @DOCUMENT_ID) AS DOCUMENT_CODE,
		-- Alur kategori: masih ada alur default aktif sebagai cadangan?
		CAST(CASE WHEN EXISTS (
			SELECT 1 FROM dbo.TB_M_WORKFLOW_DOC_H O
			WHERE O.IS_ACTIVE = 1 AND O.DOCUMENT_ID IS NULL
			AND O.DOCUMENT_LEVEL = @DOCUMENT_LEVEL AND O.CREATOR_LEVEL = @CREATOR_LEVEL
			AND O.WORKFLOW_DOC_ID <> @WORKFLOW_DOC_ID
		) THEN 1 ELSE 0 END AS BIT) AS HAS_DEFAULT_WORKFLOW,
		-- Alur default: kategori di level ini yang bergantung padanya.
		CASE WHEN @DOCUMENT_ID IS NULL THEN STUFF((
			SELECT ', ' + M.DOCUMENT_CODE
			FROM dbo.TB_M_DOCUMENT M
			WHERE M.[LEVEL] = @DOCUMENT_LEVEL AND ISNULL(M.DELETE_FLAG, 0) = 0
			AND NOT EXISTS (
				SELECT 1 FROM dbo.TB_M_WORKFLOW_DOC_H O
				WHERE O.IS_ACTIVE = 1 AND O.CREATOR_LEVEL = @CREATOR_LEVEL AND O.DOCUMENT_ID = M.DOCUMENT_ID)
			ORDER BY M.DOCUMENT_CODE
			FOR XML PATH(''), TYPE).value('.', 'VARCHAR(MAX)'), 1, 2, '') END AS DEPENDENT_CATEGORIES,
		(SELECT COUNT(*)
			FROM dbo.TB_M_USER U
			CROSS APPLY dbo.fn_WorkflowDoc_Creator(U.USERNAME) C
			WHERE ISNULL(U.DELETE_FLAG, 0) = 0 AND C.POSITION_LEVEL = @CREATOR_LEVEL) AS CREATOR_USERS,
		(SELECT COUNT(*) FROM DOCS WHERE STATUS = '0') AS IN_PROGRESS_DOCS,
		(SELECT COUNT(*) FROM DOCS WHERE STATUS = '2') AS REJECTED_DOCS;
END
GO
