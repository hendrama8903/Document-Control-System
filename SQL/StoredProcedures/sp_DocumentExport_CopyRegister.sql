-- Copy Register of a document (Document Control, 2026-11-11): every CONTROLLED copy of
-- every revision of the document the given revision belongs to, newest revision first.
-- IS_OBSOLETE = the revision is no longer in TB_R_DOCUMENT (superseded, see
-- sp_DocumentMaintenance_SupersedeRevision): its copies in circulation must be withdrawn.
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentExport_CopyRegister]
	@DOCUMENT_TRANSACTION_ID  INT
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @CODE VARCHAR(255) =
		(SELECT TOP 1 DOCUMENT_CODE FROM [dbo].[TB_R_DOCUMENT] WHERE DOCUMENT_TRANSACTION_ID = @DOCUMENT_TRANSACTION_ID);
	IF @CODE IS NULL
		SET @CODE = (SELECT TOP 1 DOCUMENT_CODE FROM [dbo].[TB_R_DOCUMENT_HISTORY] WHERE DOCUMENT_TRANSACTION_ID = @DOCUMENT_TRANSACTION_ID);

	SELECT
		E.EXPORT_ID,
		E.DOCUMENT_TRANSACTION_ID,
		E.DOCUMENT_CODE,
		E.REVISION,
		E.COPY_NO,
		E.RECIPIENT,
		E.NOTES,
		E.CREATED_BY,
		E.CREATED_DT,
		E.WITHDRAWN_BY,
		E.WITHDRAWN_DT,
		E.WITHDRAW_NOTE,
		CAST(CASE WHEN EXISTS (SELECT 1 FROM [dbo].[TB_R_DOCUMENT] D
		                       WHERE D.DOCUMENT_TRANSACTION_ID = E.DOCUMENT_TRANSACTION_ID)
		          THEN 0 ELSE 1 END AS BIT) AS IS_OBSOLETE
	FROM [dbo].[TB_R_DOCUMENT_EXPORT] E
	WHERE E.DOCUMENT_CODE = @CODE
	  AND E.PURPOSE = 'CONTROLLED'
	ORDER BY E.REVISION DESC, E.COPY_NO;
END
GO
