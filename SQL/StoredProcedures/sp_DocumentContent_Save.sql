CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentContent_Save]
	@SOURCE_TYPE   VARCHAR(10),
	@SOURCE_ID     INT,
	@FILE_PATH     VARCHAR(500),
	@CONTENT       NVARCHAR(MAX),
	@INDEX_STATUS  VARCHAR(10),
	@ERROR_MSG     VARCHAR(500) = NULL,
	@EXTRACT_METHOD VARCHAR(20) = NULL,   -- TEXT / OCR / TEXT+OCR / TEXT/NO-OCR (2026-11-06)
	@OCR_PAGES     INT = NULL
AS
BEGIN
	SET NOCOUNT ON;

	UPDATE dbo.TB_R_DOCUMENT_CONTENT
	SET FILE_PATH = @FILE_PATH, CONTENT = @CONTENT, CHAR_COUNT = LEN(@CONTENT),
		INDEX_STATUS = @INDEX_STATUS, ERROR_MSG = LEFT(@ERROR_MSG, 500), INDEXED_DT = GETDATE(),
		EXTRACT_METHOD = @EXTRACT_METHOD, OCR_PAGES = @OCR_PAGES
	WHERE SOURCE_TYPE = @SOURCE_TYPE AND SOURCE_ID = @SOURCE_ID;

	IF @@ROWCOUNT = 0
		INSERT INTO dbo.TB_R_DOCUMENT_CONTENT (SOURCE_TYPE, SOURCE_ID, FILE_PATH, CONTENT, CHAR_COUNT, INDEX_STATUS, ERROR_MSG, EXTRACT_METHOD, OCR_PAGES)
		VALUES (@SOURCE_TYPE, @SOURCE_ID, @FILE_PATH, @CONTENT, LEN(@CONTENT), @INDEX_STATUS, LEFT(@ERROR_MSG, 500), @EXTRACT_METHOD, @OCR_PAGES);
END
GO
