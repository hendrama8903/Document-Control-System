CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentMaintenance_SupersedeRevision]
	@DOCUMENT_TRANSACTION_ID	INT,		-- id revisi yang baru saja selesai disetujui
	@LOGIN_USER					VARCHAR(255),
	@RETURN_MSG					VARCHAR(MAX) OUTPUT
AS
BEGIN TRY
	DECLARE @DOCUMENT_CODE VARCHAR(50), @PREV_TRANSACTION_ID INT;

	SELECT @DOCUMENT_CODE = DOCUMENT_CODE
	FROM TB_R_DOCUMENT
	WHERE DOCUMENT_TRANSACTION_ID = @DOCUMENT_TRANSACTION_ID;

	IF @DOCUMENT_CODE IS NULL
	BEGIN
		SET @RETURN_MSG = 'ERROR: Document not found';
		RETURN 0;
	END

	-- Phase 1 (document lifecycle labels, Jul 2026): STATUS '5' (Published/Effective) is a
	-- terminal state reached AFTER '1' (Approved) once fully distributed - a previous
	-- revision sitting at '5' still needs to be superseded/archived here, same as '1'.
	SELECT TOP 1 @PREV_TRANSACTION_ID = DOCUMENT_TRANSACTION_ID
	FROM TB_R_DOCUMENT
	WHERE DOCUMENT_CODE = @DOCUMENT_CODE
	  AND DOCUMENT_TRANSACTION_ID <> @DOCUMENT_TRANSACTION_ID
	  AND STATUS IN ('1', '5');

	IF @PREV_TRANSACTION_ID IS NOT NULL
	BEGIN
		INSERT INTO [dbo].[TB_R_DOCUMENT_HISTORY]
           ([DOCUMENT_CODE]
           ,[DOCUMENT_TRANSACTION_ID]
           ,[DOCUMENT_TRANSACTION_NAME]
           ,[DOCUMENT_TYPE]
           ,[PROCESS_CODE]
           ,[COMPANY_CODE]
           ,[SECTION_CODE]
           ,[SECTION_NAME]
           ,[ITEM_CHANGED]
           ,[REASON]
           ,[EXTERNAL_FLAG]
           ,[REFERENCE_NO]
           ,[SOURCE]
           ,[DOCUMENT_DATE]
           ,[FILE_PATH]
           ,[STATUS]
           ,[REVISION]
           ,[APPROVAL_ID]
           ,[LEVEL_CODE]
           ,[DOCUMENT_ID]
           ,[DIVISION]
           ,[DIVISION_NAME]
           ,[DEPARTMENT]
           ,[DEPARTMENT_CODE]
           ,[DEPARTMENT_NAME]
           ,[CLASSIFIED]
           ,[CREATED_BY]
           ,[CREATED_DT]
           ,[CHANGED_BY]
           ,[CHANGED_DT]
           ,[DOCUMENT_CREATOR])
		SELECT [DOCUMENT_CODE]
			   ,[DOCUMENT_TRANSACTION_ID]
			   ,[DOCUMENT_TRANSACTION_NAME]
			   ,[DOCUMENT_TYPE]
			   ,[PROCESS_CODE]
			   ,[COMPANY_CODE]
			   ,[SECTION_CODE]
			   ,[SECTION_NAME]
			   ,[ITEM_CHANGED]
			   ,[REASON]
			   ,[EXTERNAL_FLAG]
			   ,[REFERENCE_NO]
			   ,[SOURCE]
			   ,[DOCUMENT_DATE]
			   ,[FILE_PATH]
			   ,'4' -- OBSOLETE, dipaksa terlepas dari STATUS asal (bisa '1' APPROVED atau '5' PUBLISHED)
			   ,[REVISION]
			   ,[APPROVAL_ID]
			   ,[LEVEL_CODE]
			   ,[DOCUMENT_ID]
				 ,[DIVISION]
				 ,[DIVISION_NAME]
				 ,[DEPARTMENT]
				 ,[DEPARTMENT_CODE]
				 ,[DEPARTMENT_NAME]
				 ,[CLASSIFIED]
			   ,[CREATED_BY]
			   ,[CREATED_DT]
			   ,@LOGIN_USER
			   ,GETDATE()
			   ,[DOCUMENT_CREATOR]
		FROM TB_R_DOCUMENT
		WHERE DOCUMENT_TRANSACTION_ID = @PREV_TRANSACTION_ID;

		-- Stamp Layout tahap 3 (2026-11-11): revisi baru mewarisi posisi stempel revisi lama.
		-- Saat Accept di Document Registration QMS cukup memastikan posisinya masih cocok.
		IF OBJECT_ID('dbo.TB_R_DOCUMENT_STAMP_LAYOUT', 'U') IS NOT NULL
			AND EXISTS (SELECT 1 FROM dbo.TB_R_DOCUMENT_STAMP_LAYOUT WHERE DOCUMENT_TRANSACTION_ID = @PREV_TRANSACTION_ID)
			AND NOT EXISTS (SELECT 1 FROM dbo.TB_R_DOCUMENT_STAMP_LAYOUT WHERE DOCUMENT_TRANSACTION_ID = @DOCUMENT_TRANSACTION_ID)
		BEGIN
			DECLARE @NEW_REVISION INT, @PREV_REVISION INT, @INHERIT_SOURCE VARCHAR(20);
			SELECT @NEW_REVISION = ISNULL(REVISION, 0) FROM TB_R_DOCUMENT WHERE DOCUMENT_TRANSACTION_ID = @DOCUMENT_TRANSACTION_ID;
			SELECT @PREV_REVISION = ISNULL(REVISION, 0) FROM TB_R_DOCUMENT WHERE DOCUMENT_TRANSACTION_ID = @PREV_TRANSACTION_ID;
			SELECT TOP 1 @INHERIT_SOURCE = SOURCE FROM dbo.TB_R_DOCUMENT_STAMP_LAYOUT
			WHERE DOCUMENT_TRANSACTION_ID = @PREV_TRANSACTION_ID ORDER BY CASE SOURCE WHEN 'CUSTOM' THEN 0 ELSE 1 END;

			INSERT INTO dbo.TB_R_DOCUMENT_STAMP_LAYOUT
				(DOCUMENT_TRANSACTION_ID, REVISION, STAMP_TYPE, ORIENTATION, POS_X, POS_Y, WIDTH_PCT, SOURCE, CREATED_BY, CREATED_DT)
			SELECT @DOCUMENT_TRANSACTION_ID, @NEW_REVISION, STAMP_TYPE, ORIENTATION, POS_X, POS_Y, WIDTH_PCT, SOURCE, @LOGIN_USER, GETDATE()
			FROM dbo.TB_R_DOCUMENT_STAMP_LAYOUT
			WHERE DOCUMENT_TRANSACTION_ID = @PREV_TRANSACTION_ID
			  -- Tahap 4: posisi khusus halaman tidak diwariskan (isi halaman revisi baru berbeda).
			  AND PAGE_NO IS NULL;

			INSERT INTO dbo.TB_R_DOCUMENT_STAMP_LAYOUT_LOG
				(DOCUMENT_TRANSACTION_ID, REVISION, ACTION, SOURCE, POSITIONS, REASON, CREATED_BY, CREATED_DT)
			VALUES (@DOCUMENT_TRANSACTION_ID, @NEW_REVISION, 'INHERIT', ISNULL(@INHERIT_SOURCE, 'CUSTOM'), NULL,
				'From Rev.' + RIGHT('0' + CAST(@PREV_REVISION AS VARCHAR(10)), 2), @LOGIN_USER, GETDATE());
		END

		DELETE FROM TB_R_DOCUMENT WHERE DOCUMENT_TRANSACTION_ID = @PREV_TRANSACTION_ID;

		-- Retire registrasi P4D dokumen lama DI SINI (bukan lagi saat revisi
		-- dibuat, lihat sp_DocumentMaintenance_Insert) - dokumen lama baru
		-- benar-benar berhenti jadi versi resmi sekarang (revisi barunya baru
		-- saja disetujui penuh), jadi baru sekarang wajar hilang dari grid P4D
		-- Maintenance. Selama revisi masih Draft/pending approval, dokumen lama
		-- tetap terdaftar & terlihat di P4D seperti seharusnya (request Hendra
		-- 2026-08-16, ditemukan lewat pengujian).
		UPDATE [dbo].[TB_R_CTRL_DOCUMENT]
		SET DELETE_FLAG = '1',
			CHANGED_BY = @LOGIN_USER,
			CHANGED_DT = GETDATE()
		WHERE DOCUMENT_TRANSACTION_ID = @PREV_TRANSACTION_ID
			AND ISNULL(DELETE_FLAG, 0) = 0;
	END

	SET @RETURN_MSG = 'OK';
	RETURN 1;
END TRY
BEGIN CATCH
	SET @RETURN_MSG = 'ERROR: ' + ERROR_PROCEDURE() + ': ' + ERROR_MESSAGE() + ', at line = ' + CAST(ERROR_LINE() AS VARCHAR);
	RETURN 0;
END CATCH
GO
