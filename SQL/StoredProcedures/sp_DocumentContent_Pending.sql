-- Dokumen yang perlu (di)indeks isinya: belum pernah, atau file-nya sudah
-- berganti sejak diindeks (lihat SQL/DocumentFullTextSearch_Migration.sql).
-- File yang gagal/hilang dicoba lagi paling cepat 1 hari kemudian. Dokumen yang
-- terindeks KOSONG sebelum OCR ada (EXTRACT_METHOD NULL / TEXT) diindeks ulang sekali
-- supaya PDF scan ikut dibaca OCR; TEXT/NO-OCR (OCR tidak tersedia) dicoba tiap hari.
CREATE OR ALTER PROCEDURE [dbo].[sp_DocumentContent_Pending]
	@MAX_ROWS INT = 100
AS
BEGIN
	SET NOCOUNT ON;

	SELECT TOP (@MAX_ROWS) X.SOURCE_TYPE, X.SOURCE_ID, X.FILE_PATH
	FROM (
		SELECT 'INTERNAL' AS SOURCE_TYPE, D.DOCUMENT_TRANSACTION_ID AS SOURCE_ID, LTRIM(RTRIM(D.FILE_PATH)) AS FILE_PATH, D.CREATED_DT
		FROM dbo.TB_R_DOCUMENT D
		WHERE ISNULL(D.DELETE_FLAG, 0) = 0 AND NULLIF(LTRIM(RTRIM(D.FILE_PATH)), '') IS NOT NULL
		UNION ALL
		SELECT 'EXTERNAL', E.EXTERNAL_DOCUMENT_ID, LTRIM(RTRIM(E.FILE_PATH)), E.CREATED_DT
		FROM dbo.TB_M_EXTERNAL_DOCUMENT E
		WHERE ISNULL(E.DELETE_FLAG, 0) = 0 AND NULLIF(LTRIM(RTRIM(E.FILE_PATH)), '') IS NOT NULL
	) X
	LEFT JOIN dbo.TB_R_DOCUMENT_CONTENT C ON C.SOURCE_TYPE = X.SOURCE_TYPE AND C.SOURCE_ID = X.SOURCE_ID
	WHERE C.SOURCE_ID IS NULL
	   OR C.FILE_PATH <> X.FILE_PATH
	   OR (C.INDEX_STATUS IN ('ERROR', 'MISSING') AND C.INDEXED_DT < DATEADD(DAY, -1, GETDATE()))
	   OR (C.INDEX_STATUS = 'EMPTY' AND ISNULL(C.EXTRACT_METHOD, 'TEXT') = 'TEXT')
	   OR (C.EXTRACT_METHOD = 'TEXT/NO-OCR' AND C.INDEXED_DT < DATEADD(DAY, -1, GETDATE()))
	ORDER BY X.CREATED_DT DESC;
END
GO
