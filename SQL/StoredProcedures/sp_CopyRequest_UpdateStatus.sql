CREATE OR ALTER PROCEDURE [dbo].[sp_CopyRequest_UpdateStatus]
	@REQUEST_ID    INT,
	@STATUS        CHAR(1),
	@LOGIN_USER    VARCHAR(255),
	@RETURN_MSG    VARCHAR(MAX) OUTPUT
AS
BEGIN TRY
	SET NOCOUNT ON;

	IF NOT EXISTS (SELECT 1 FROM TB_R_COPY_REQUEST_H WHERE REQUEST_ID = @REQUEST_ID AND DELETE_FLAG = 0)
	BEGIN
		SET @RETURN_MSG = 'ERROR: Request not found';
		RETURN 0;
	END

	UPDATE [dbo].[TB_R_COPY_REQUEST_H]
	SET STATUS = @STATUS, CHANGED_BY = @LOGIN_USER, CHANGED_DT = GETDATE()
	WHERE REQUEST_ID = @REQUEST_ID;

	SET @RETURN_MSG = 'Successfully Updated';
	RETURN 1;
END TRY
BEGIN CATCH
	SET @RETURN_MSG = 'ERROR: ' + ERROR_PROCEDURE() +': '+ ERROR_MESSAGE() + ', at line = ' +  CAST(ERROR_LINE() AS VARCHAR);
	RETURN 0;
END CATCH
GO
